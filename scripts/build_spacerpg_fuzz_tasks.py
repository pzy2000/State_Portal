#!/usr/bin/env python3
"""Build a SpaceRPG-only state-fuzz task set from every spec under ``specs/spacerpg``.

Mirrors ``benchmarks/state_loop/tasks_2048.yaml`` but for SpaceRPG: one C3
fuzz-bench task per oracle spec so ``fuzz-bench`` can exercise the full SpaceRPG
robustness surface (all injection kinds) across all specs.

Source of truth is ``specs/spacerpg/*.yaml``. Output is ``benchmarks/state_loop/
tasks_spacerpg.yaml``. Nothing else is modified.

Usage:
    python scripts/build_spacerpg_fuzz_tasks.py
"""
from __future__ import annotations

import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
SPEC_DIR = ROOT / "specs" / "spacerpg"
OUTPUT = ROOT / "benchmarks" / "state_loop" / "tasks_spacerpg.yaml"
REPO = "games/SpaceRPG"
BENCHMARK = "SpaceRPG"
BUDGET_MS = 180_000

if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from warptest.c1_evaluation import visual_oracle  # noqa: E402


def _task_id(spec_path: Path) -> str:
    stem = spec_path.stem.strip().lower()
    return stem if stem.startswith("spacerpg-") else f"spacerpg-{stem}"


def _state_description(spec: dict) -> str:
    name = str(spec.get("name") or "").strip()
    value = visual_oracle(spec)
    visual = value if isinstance(value, dict) else {}
    desc = str(visual.get("description") or "").strip()
    parts = [p for p in (name, desc) if p]
    text = " ".join(parts) or "Reach the SpaceRPG deep state described by this oracle spec."
    return " ".join(text.split())


def _tags(spec: dict) -> list[str]:
    tags = ["state-loop", "spacerpg", "fuzz"]
    for tag in spec.get("tags", []) or []:
        tag = str(tag)
        if tag not in tags:
            tags.append(tag)
    return tags


def build() -> list[dict]:
    spec_paths = sorted(SPEC_DIR.glob("*.yaml"))
    if not spec_paths:
        raise SystemExit(f"No specs found under {SPEC_DIR}")
    tasks: list[dict] = []
    for spec_path in spec_paths:
        spec = yaml.safe_load(spec_path.read_text(encoding="utf-8"))
        if not isinstance(spec, dict) or spec.get("benchmark") != BENCHMARK:
            print(f"  skip (not a SpaceRPG spec): {spec_path.name}")
            continue
        tasks.append(
            {
                "id": _task_id(spec_path),
                "benchmark": BENCHMARK,
                "repo": REPO,
                "state_description": _state_description(spec),
                "oracle_spec": str(spec_path.relative_to(ROOT)),
                "tags": _tags(spec),
                "budget_ms": BUDGET_MS,
            }
        )
    return tasks


def main() -> int:
    tasks = build()
    header = (
        "# SpaceRPG-only task set for C3 state fuzzing (fuzz-bench).\n"
        "# Auto-generated by scripts/build_spacerpg_fuzz_tasks.py from every spec under\n"
        "# specs/spacerpg/*.yaml. Runs the SpaceRPG robustness mutations (all injection kinds)\n"
        "# in isolation, mirroring benchmarks/state_loop/tasks_2048.yaml.\n"
        "# Do not edit by hand; re-run the generator instead.\n"
    )
    body = yaml.safe_dump({"tasks": tasks}, sort_keys=False, allow_unicode=True, width=100000)
    OUTPUT.write_text(header + body, encoding="utf-8")
    print(f"Wrote {len(tasks)} SpaceRPG fuzz tasks to {OUTPUT.relative_to(ROOT)}")
    print("task ids:", ", ".join(t["id"] for t in tasks))
    return 0


if __name__ == "__main__":
    sys.exit(main())
