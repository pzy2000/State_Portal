#!/usr/bin/env python3
"""Build the default C3-only task manifest.

``benchmarks/state_loop/tasks.yaml`` remains the C1 State Loop manifest.  This
script filters its already-supported C3 entries, then appends the generated
OpenRA gameplay set and the generated jynew set so neither C1 nor unrelated
native profiles are pulled into the C3 default by accident.
"""
from __future__ import annotations

from pathlib import Path
from typing import Any

import yaml


ROOT = Path(__file__).resolve().parents[1]
STATE_LOOP_SOURCE = ROOT / "benchmarks" / "state_loop" / "tasks.yaml"
OPENRA_SOURCE = ROOT / "benchmarks" / "state_loop" / "tasks_openra.yaml"
JYNEW_SOURCE = ROOT / "benchmarks" / "state_loop" / "tasks_jynew.yaml"
OUTPUT = ROOT / "benchmarks" / "state_loop" / "tasks_c3.yaml"
SUPPORTED_FROM_STATE_LOOP = {"2048", "SpaceRPG", "DatingSim", "luanti"}


def _load_tasks(path: Path) -> list[dict[str, Any]]:
    payload = yaml.safe_load(path.read_text(encoding="utf-8"))
    if not isinstance(payload, dict) or not isinstance(payload.get("tasks"), list):
        raise SystemExit(f"Task manifest must contain a tasks list: {path}")
    return [task for task in payload["tasks"] if isinstance(task, dict)]


def build() -> list[dict[str, Any]]:
    if not OPENRA_SOURCE.exists():
        raise SystemExit(f"Missing {OPENRA_SOURCE}; run scripts/build_openra_fuzz_tasks.py first.")
    if not JYNEW_SOURCE.exists():
        raise SystemExit(f"Missing {JYNEW_SOURCE}; run scripts/build_jynew_fuzz_tasks.py first.")
    tasks = [
        task for task in _load_tasks(STATE_LOOP_SOURCE)
        if str(task.get("benchmark")) in SUPPORTED_FROM_STATE_LOOP
    ]
    tasks.extend(_load_tasks(OPENRA_SOURCE))
    tasks.extend(_load_tasks(JYNEW_SOURCE))
    ids = [str(task.get("id")) for task in tasks]
    if len(ids) != len(set(ids)):
        raise SystemExit("C3 task ids must be unique")
    return tasks


def main() -> int:
    tasks = build()
    header = (
        "# Default C3 state-fuzzing task set.\n"
        "# Auto-generated by scripts/build_c3_fuzz_tasks.py.\n"
        "# It is intentionally distinct from tasks.yaml, which remains the C1 State Loop manifest.\n"
        "# Do not edit by hand; regenerate after changing source task manifests.\n"
    )
    body = yaml.safe_dump({"tasks": tasks}, sort_keys=False, allow_unicode=True, width=100000)
    OUTPUT.write_text(header + body, encoding="utf-8")
    print(f"Wrote {len(tasks)} C3 fuzz tasks to {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
