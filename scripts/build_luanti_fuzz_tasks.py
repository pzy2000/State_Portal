#!/usr/bin/env python3
"""Build a Luanti-only state-fuzz task set from the world-class specs under ``specs/luanti``.

Mirrors ``scripts/build_spacerpg_fuzz_tasks.py`` (and ``benchmarks/state_loop/
tasks_2048.yaml``) but for Luanti: one C3 fuzz-bench task per world-class oracle
spec so ``fuzz-bench`` can exercise the full Luanti engine-path robustness surface.

Only non-C1 world-class specs are emitted. The C3 fuzz warm session is a headless
``luantiserver`` with no online player (``LuantiWarmSession(render=False)``), so
specs that touch online-player state (``_spec_needs_client`` is True) cannot be
synthesized there and are skipped.

Source of truth is ``specs/luanti/*.yaml``. Output is ``benchmarks/state_loop/
tasks_luanti.yaml``. Nothing else is modified.

Usage:
    python scripts/build_luanti_fuzz_tasks.py
"""
from __future__ import annotations

import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
SPEC_DIR = ROOT / "specs" / "luanti"
OUTPUT = ROOT / "benchmarks" / "state_loop" / "tasks_luanti.yaml"
REPO = "games/luanti"
BENCHMARK = "luanti"
BUDGET_MS = 120_000

sys.path.insert(0, str(ROOT))
from warptest.luanti_runtime import _spec_needs_client  # noqa: E402
from warptest.c1_evaluation import visual_oracle  # noqa: E402


def _task_id(spec_path: Path) -> str:
    stem = spec_path.stem.strip().lower()
    return stem if stem.startswith("luanti-") else f"luanti-{stem}"


def _state_description(spec: dict) -> str:
    name = str(spec.get("name") or "").strip()
    value = visual_oracle(spec)
    visual = value if isinstance(value, dict) else {}
    desc = str(visual.get("description") or "").strip()
    parts = [p for p in (name, desc) if p]
    text = " ".join(parts) or "Reach the Luanti deep state described by this oracle spec."
    return " ".join(text.split())


def _tags(spec: dict) -> list[str]:
    tags = ["state-loop", "luanti", "fuzz"]
    for tag in spec.get("tags", []) or []:
        tag = str(tag)
        if tag not in tags:
            tags.append(tag)
    return tags


def build() -> list[dict]:
    spec_paths = sorted(SPEC_DIR.glob("*.yaml"))
    if not spec_paths:
        raise SystemExit(f"No specs found under {SPEC_DIR}")
    tasks: list[dict] = []
    for spec_path in spec_paths:
        spec = yaml.safe_load(spec_path.read_text(encoding="utf-8"))
        if not isinstance(spec, dict) or spec.get("benchmark") != BENCHMARK:
            print(f"  skip (not a Luanti spec): {spec_path.name}")
            continue
        if "c1" in (spec.get("tags") or []):
            print(f"  skip (C1-only): {spec_path.name}")
            continue
        if _spec_needs_client(spec):
            # Player/visual spec: needs an online player + rendered client, which the
            # headless fuzz warm session does not provide. Not fuzzable on this path.
            print(f"  skip (needs online-player client): {spec_path.name}")
            continue
        tasks.append(
            {
                "id": _task_id(spec_path),
                "benchmark": BENCHMARK,
                "repo": REPO,
                "state_description": _state_description(spec),
                "oracle_spec": str(spec_path.relative_to(ROOT)),
                "tags": _tags(spec),
                "budget_ms": BUDGET_MS,
            }
        )
    return tasks


def main() -> int:
    tasks = build()
    header = (
        "# Luanti-only task set for C3 state fuzzing (fuzz-bench).\n"
        "# Auto-generated by scripts/build_luanti_fuzz_tasks.py from the world-class\n"
        "# non-C1 specs under specs/luanti/*.yaml. Runs the Luanti engine-path robustness\n"
        "# mutations in isolation, mirroring benchmarks/state_loop/tasks_spacerpg.yaml.\n"
        "# Player/visual specs are excluded (the headless fuzz session has no online\n"
        "# player). Do not edit by hand; re-run the generator instead.\n"
    )
    body = yaml.safe_dump({"tasks": tasks}, sort_keys=False, allow_unicode=True, width=100000)
    OUTPUT.write_text(header + body, encoding="utf-8")
    print(f"Wrote {len(tasks)} Luanti fuzz tasks to {OUTPUT.relative_to(ROOT)}")
    print("task ids:", ", ".join(t["id"] for t in tasks))
    return 0


if __name__ == "__main__":
    sys.exit(main())
