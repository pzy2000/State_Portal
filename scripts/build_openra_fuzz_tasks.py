#!/usr/bin/env python3
"""Build the gameplay-only OpenRA C3 fuzz task set.

The OpenRA utility-map specs validate static map metadata and are intentionally
excluded: C3 fuzzing must exercise the live gameplay probe. C1-tagged gameplay
specs are also excluded so the formal C1 expansion cannot change C3. Source of truth is
``specs/openra/*.yaml``; the generated output is
``benchmarks/state_loop/tasks_openra.yaml``.
"""
from __future__ import annotations

import sys
from pathlib import Path
from typing import Any

import yaml


ROOT = Path(__file__).resolve().parents[1]
SPEC_DIR = ROOT / "specs" / "openra"
OUTPUT = ROOT / "benchmarks" / "state_loop" / "tasks_openra.yaml"
BENCHMARK = "OpenRA"
REPO = "games/OpenRA"
BUDGET_MS = 180_000
GAMEPLAY_STRATEGY = "openra_gameplay_production_validate"

if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from warptest.c1_evaluation import visual_oracle  # noqa: E402


def is_gameplay_spec(spec: dict[str, Any]) -> bool:
    checkpoint = spec.get("checkpoint") if isinstance(spec.get("checkpoint"), dict) else {}
    strategies = checkpoint.get("allowed_strategies") if isinstance(checkpoint, dict) else []
    return (
        spec.get("benchmark") == BENCHMARK
        and isinstance(strategies, list)
        and GAMEPLAY_STRATEGY in strategies
        and "c1" not in (spec.get("tags") or [])
    )


def _task_id(spec_path: Path) -> str:
    return f"openra-{spec_path.stem}"


def _state_description(spec: dict[str, Any]) -> str:
    name = str(spec.get("name") or "").strip()
    value = visual_oracle(spec)
    visual = value if isinstance(value, dict) else {}
    description = str(visual.get("description") or "").strip()
    return " ".join(part for part in (name, description) if part) or "OpenRA gameplay production checkpoint."


def _tags(spec: dict[str, Any]) -> list[str]:
    tags = ["state-loop", "openra", "fuzz", "gameplay", "production"]
    for value in spec.get("tags") or []:
        value = str(value)
        if value not in tags:
            tags.append(value)
    return tags


def build() -> list[dict[str, Any]]:
    tasks: list[dict[str, Any]] = []
    for spec_path in sorted(SPEC_DIR.glob("*.yaml")):
        spec = yaml.safe_load(spec_path.read_text(encoding="utf-8"))
        if not isinstance(spec, dict) or not is_gameplay_spec(spec):
            continue
        tasks.append(
            {
                "id": _task_id(spec_path),
                "benchmark": BENCHMARK,
                "repo": REPO,
                "state_description": _state_description(spec),
                "oracle_spec": str(spec_path.relative_to(ROOT)),
                "tags": _tags(spec),
                "budget_ms": BUDGET_MS,
            }
        )
    if not tasks:
        raise SystemExit(f"No {GAMEPLAY_STRATEGY} specs found under {SPEC_DIR}")
    return tasks


def main() -> int:
    tasks = build()
    header = (
        "# OpenRA gameplay-only task set for C3 state fuzzing (fuzz-bench).\n"
        "# Auto-generated by scripts/build_openra_fuzz_tasks.py from specs/openra/*.yaml.\n"
        "# Only non-C1 live openra_gameplay_production_validate specs are included; utility-map\n"
        "# metadata validation is deliberately outside the C3 gameplay surface. Do not edit by hand.\n"
    )
    body = yaml.safe_dump({"tasks": tasks}, sort_keys=False, allow_unicode=True, width=100000)
    OUTPUT.write_text(header + body, encoding="utf-8")
    print(f"Wrote {len(tasks)} OpenRA C3 fuzz tasks to {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
