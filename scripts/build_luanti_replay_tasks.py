#!/usr/bin/env python3
"""Build the Luanti replay task set from the gold replay specs.

Mirrors ``scripts/build_luanti_fuzz_tasks.py`` but for the SWE-bench-style replay
dataset: one task per spec under ``specs/luanti/replay/*.yaml``. These reference the
replay specs via ``oracle_spec`` so they can be listed / tracked alongside the fuzz
task sets; actual regression verification is done by ``verify_luanti_replay.py``.

Source of truth: ``specs/luanti/replay/*.yaml``. Output:
``benchmarks/state_loop/tasks_luanti_replay.yaml``.

Usage:
    python scripts/build_luanti_replay_tasks.py
"""
from __future__ import annotations

from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
SPEC_DIR = ROOT / "specs" / "luanti" / "replay"
OUTPUT = ROOT / "benchmarks" / "state_loop" / "tasks_luanti_replay.yaml"
REPO = "games/luanti"
BENCHMARK = "luanti"
BUDGET_MS = 60_000


def build() -> list[dict]:
    tasks: list[dict] = []
    for spec_path in sorted(SPEC_DIR.glob("*.yaml")):
        spec = yaml.safe_load(spec_path.read_text(encoding="utf-8"))
        if not isinstance(spec, dict) or spec.get("benchmark") != BENCHMARK:
            continue
        source = spec.get("source") or {}
        tasks.append(
            {
                "id": f"luanti-replay-{spec_path.stem}",
                "benchmark": BENCHMARK,
                "repo": REPO,
                "state_description": " ".join(str(spec.get("name") or spec_path.stem).split()),
                "oracle_spec": str(spec_path.relative_to(ROOT)),
                "tags": ["state-loop", "luanti", "replay"],
                "budget_ms": int(spec.get("timeout_s", 45)) * 1000 or BUDGET_MS,
                "replay_source": {
                    "upstream_repo": source.get("upstream_repo"),
                    "pr_number": source.get("pr_number"),
                    "pre_fix_sha": source.get("pre_fix_sha"),
                    "post_fix_sha": source.get("post_fix_sha"),
                },
            }
        )
    return tasks


def main() -> int:
    tasks = build()
    if not tasks:
        raise SystemExit(f"No replay specs found under {SPEC_DIR}")
    header = (
        "# Luanti replay (regression) task set.\n"
        "# Auto-generated by scripts/build_luanti_replay_tasks.py from\n"
        "# specs/luanti/replay/*.yaml. Each task points at a replay spec whose\n"
        "# EXPLICIT defect oracle + pre/post-fix commits are verified by\n"
        "# scripts/verify_luanti_replay.py (five-state verdict). Do not edit by hand.\n"
    )
    body = yaml.safe_dump({"tasks": tasks}, sort_keys=False, allow_unicode=True, width=100000)
    OUTPUT.write_text(header + body, encoding="utf-8")
    print(f"Wrote {len(tasks)} luanti replay task(s) to {OUTPUT.relative_to(ROOT)}")
    for task in tasks:
        print(f"  {task['id']}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
