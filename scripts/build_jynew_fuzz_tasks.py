#!/usr/bin/env python3
"""Build the jynew C3 fuzz task set.

Source of truth is ``specs/jynew/*.yaml``; the generated output is
``benchmarks/state_loop/tasks_jynew.yaml``. Every jynew spec currently uses the
``jynew_utility_save_validate`` strategy with a ``synthesized_state`` target.
Specs tagged ``c1`` belong only to the formal C1 universe and are deliberately
excluded so adding C1 tasks cannot silently expand C3.
"""
from __future__ import annotations

import sys
from pathlib import Path
from typing import Any

import yaml


ROOT = Path(__file__).resolve().parents[1]
SPEC_DIR = ROOT / "specs" / "jynew"
OUTPUT = ROOT / "benchmarks" / "state_loop" / "tasks_jynew.yaml"
BENCHMARK = "jynew"
REPO = "games/jynew"
BUDGET_MS = 240_000
STRATEGY = "jynew_utility_save_validate"
TARGET_KIND = "synthesized_state"

if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from warptest.c1_evaluation import visual_oracle  # noqa: E402


def is_fuzzable_spec(spec: dict[str, Any]) -> bool:
    checkpoint = spec.get("checkpoint") if isinstance(spec.get("checkpoint"), dict) else {}
    strategies = checkpoint.get("allowed_strategies") if isinstance(checkpoint, dict) else []
    target = spec.get("target") if isinstance(spec.get("target"), dict) else {}
    return (
        spec.get("benchmark") == BENCHMARK
        and isinstance(strategies, list)
        and STRATEGY in strategies
        and target.get("kind") == TARGET_KIND
        and "c1" not in (spec.get("tags") or [])
    )


def _task_id(spec_path: Path) -> str:
    return f"jynew-{spec_path.stem}"


def _state_description(spec: dict[str, Any]) -> str:
    name = str(spec.get("name") or "").strip()
    value = visual_oracle(spec)
    visual = value if isinstance(value, dict) else {}
    description = str(visual.get("description") or "").strip()
    return " ".join(part for part in (name, description) if part) or "jynew synthesized-state checkpoint."


def _tags(spec: dict[str, Any]) -> list[str]:
    tags = ["state-loop", "jynew", "fuzz", "synthesized-state"]
    for value in spec.get("tags") or []:
        value = str(value)
        if value not in tags:
            tags.append(value)
    return tags


def build() -> list[dict[str, Any]]:
    tasks: list[dict[str, Any]] = []
    for spec_path in sorted(SPEC_DIR.glob("*.yaml")):
        spec = yaml.safe_load(spec_path.read_text(encoding="utf-8"))
        if not isinstance(spec, dict) or not is_fuzzable_spec(spec):
            continue
        tasks.append(
            {
                "id": _task_id(spec_path),
                "benchmark": BENCHMARK,
                "repo": REPO,
                "state_description": _state_description(spec),
                "oracle_spec": str(spec_path.relative_to(ROOT)),
                "tags": _tags(spec),
                "budget_ms": BUDGET_MS,
            }
        )
    if not tasks:
        raise SystemExit(f"No {STRATEGY}/{TARGET_KIND} specs found under {SPEC_DIR}")
    return tasks


def main() -> int:
    tasks = build()
    header = (
        "# jynew task set for C3 state fuzzing (fuzz-bench).\n"
        "# Auto-generated by scripts/build_jynew_fuzz_tasks.py from specs/jynew/*.yaml.\n"
        "# Only non-C1 jynew_utility_save_validate + synthesized_state specs are included. "
        "Do not edit by hand.\n"
    )
    body = yaml.safe_dump({"tasks": tasks}, sort_keys=False, allow_unicode=True, width=100000)
    OUTPUT.write_text(header + body, encoding="utf-8")
    print(f"Wrote {len(tasks)} jynew C3 fuzz tasks to {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
