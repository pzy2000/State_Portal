def _run_phase(
    *,
    runtime: Any,
    client: Any,
    instruction: str,
    phase_dir: Path,
    max_steps: int,
    observer: FixedVisualBridge | None = None,
    task_id: str | None = None,
) -> PhaseResult:
    phase_dir.mkdir(parents=True, exist_ok=True)
    phase_start = time.perf_counter()
    history: list[str] = []
    actions: list[dict[str, Any]] = []
    last_shot: str | None = None
    phase_incomplete = False
    hidden_grader_ms = 0.0
    metadata = getattr(client, "metadata", None)
    native_exec_enabled = bool(
        isinstance(metadata, dict) and metadata.get("native_exec_enabled")
    )
    raw_screenshot_observation = bool(
        native_exec_enabled
        or (
            isinstance(metadata, dict)
            and (
                metadata.get("raw_screenshot_observation") is True
                or metadata.get("worker_observation_mode") == "screenshot"
            )
        )
    )
    action_execution_owner = (
        str(metadata.get("action_execution_owner") or "worker")
        if isinstance(metadata, dict)
        else "parent_runtime"
    )
    worker_executes_action = native_exec_enabled or action_execution_owner == "worker"
    foreground_required = bool(
        native_exec_enabled
        or (isinstance(metadata, dict) and metadata.get("foreground_required") is True)
    )
    execution_backend = (
        str(metadata.get("execution_backend") or "")
        if isinstance(metadata, dict)
        else ""
    )
    width, height = _runtime_dimensions(runtime, native_exec_enabled=native_exec_enabled)
    session_id = str(
        getattr(runtime, "session_id", None)
        or task_id
        or f"phase-{phase_dir.name}"
    )
    for step in range(1, max_steps + 1):
        raise_if_task_timed_out()
        if foreground_required:
            # Bring the real OS window forward before capturing, so the frame
            # handed to the native worker matches what its pyautogui exec is
            # about to click.
            try:
                native_window.focus_runtime(runtime)
            except Exception as error:
                actions.append(
                    {
                        "step": step,
                        "error": run_context.safe_error_text(str(error), limit=1000),
                        "infrastructure_error": True,
                        "diagnostic_screenshot": last_shot,
                    }
                )
                phase_incomplete = True
                break
        capture = _capture_fresh_runtime(
            runtime,
            phase_dir / f"step-{step:03d}.png",
            native_exec_enabled=native_exec_enabled,
        )
        hidden_grader_ms += capture.retry_elapsed_ms
        shot = capture.screenshot
        capture_diagnostic: dict[str, Any] = {
            "capture_attempts": capture.attempts,
        }
        if capture.capture_errors:
            capture_diagnostic["capture_errors"] = capture.capture_errors
        if shot is None:
            actions.append(
                {
                    "step": step,
                    "error": "screenshot_capture_failed",
                    "infrastructure_error": True,
                    "diagnostic_screenshot": last_shot,
                    **capture_diagnostic,
                }
            )
            phase_incomplete = True
            break
        last_shot = shot
        captured_frame_id = getattr(runtime, "last_policy_frame_id", step)
        if (
            isinstance(captured_frame_id, bool)
            or not isinstance(captured_frame_id, int)
            or captured_frame_id < 0
        ):
            actions.append(
                {
                    "step": step,
                    "error": "runtime did not expose a valid captured frame id",
                    "infrastructure_error": True,
                    **capture_diagnostic,
                }
            )
            phase_incomplete = True
            break
        capture_backend = getattr(runtime, "capture_backend", None)
        if not isinstance(capture_backend, str) or not capture_backend:
            capture_backend = (
                "playwright_page_screenshot_v1"
                if getattr(runtime, "page", None) is not None
                else ""
            )
        if execution_backend == BACKGROUND_PIXEL_BACKEND and not capture_backend:
            actions.append(
                {
                    "step": step,
                    "error": "background runtime did not identify its capture backend",
                    "infrastructure_error": True,
                    **capture_diagnostic,
                }
            )
            phase_incomplete = True
            break
        input_backend = getattr(runtime, "input_backend", None)
        if not isinstance(input_backend, str) or not input_backend:
            input_backend = (
                "playwright_page_input_v1"
                if getattr(runtime, "page", None) is not None
                else ""
            )
        if execution_backend == BACKGROUND_PIXEL_BACKEND and not input_backend:
            actions.append(
                {
                    "step": step,
                    "error": "background runtime did not identify its input backend",
                    "infrastructure_error": True,
                    **capture_diagnostic,
                }
            )
            phase_incomplete = True
            break
        try:
            observation = None
            if raw_screenshot_observation:
                # The native worker's decision/reflection models see the raw
                # screenshot directly (upstream Agent-S behavior); the fixed
                # visual observer is unused, so skip it and send a placeholder.
                observation = "native" if native_exec_enabled else "raw_screenshot"
            elif observer is not None:
                observation = observer.observe(
                    Path(shot),
                    instruction=instruction,
                    width=width,
                    height=height,
                )
            prediction = _call_policy_next_action(
                client,
                task=task_id,
                instruction=instruction,
                screenshot=Path(shot),
                history=history,
                observation=observation,
                width=width,
                height=height,
                session_id=session_id,
                frame_id=captured_frame_id,
                capture_backend=capture_backend,
            )
            action = _coerce_action(prediction)
            action_batch = _prediction_action_batch(prediction)
        except Exception as error:
            infra = _is_infrastructure_error(error)
            actions.append(
                {
                    "step": step,
                    "error": run_context.safe_error_text(str(error), limit=1000),
                    "infrastructure_error": infra,
                    # The policy failed before an action batch existed, but the
                    # parent had already captured and bound a real policy frame.
                    # Keep that background provenance visible without inventing
                    # a batch id, input mapping, or execution receipt.
                    "execution_backend": execution_backend or None,
                    "session_id": session_id,
                    "frame_id": captured_frame_id,
                    "capture_backend": capture_backend,
                    "input_backend": input_backend,
                    "target_pid": _runtime_target_pid(runtime),
                    "action_execution_owner": action_execution_owner,
                    "coordinate_space": (
                        metadata.get("coordinate_space")
                        if isinstance(metadata, dict)
                        else None
                    ),
                    **capture_diagnostic,
                }
            )
            phase_incomplete = phase_incomplete or infra
            break
        actions.append(
            {
                **_action_dict(action, step=step),
                "execution_backend": execution_backend or None,
                "session_id": session_id,
                "frame_id": captured_frame_id,
                "capture_backend": capture_backend,
                "input_backend": input_backend,
                "target_pid": _runtime_target_pid(runtime),
                "action_execution_owner": action_execution_owner,
                "coordinate_space": (
                    metadata.get("coordinate_space")
                    if isinstance(metadata, dict)
                    else None
                ),
                "structured_actions": [
                    _action_dict(item, step=step) for item in action_batch
                ],
                "input_mapping": _background_input_mapping(
                    action_batch,
                    width=width,
                    height=height,
                    input_backend=input_backend,
                    runtime=runtime,
                ),
                **capture_diagnostic,
                **(_native_info_fields(prediction) if raw_screenshot_observation else {}),
            }
        )
        history.append(f"{action.kind}({action.x},{action.y},{action.key})")
        if action.kind in {"done", "fail"}:
            break
        if worker_executes_action:
            # The native worker child already executed the action (pyautogui
            # exec against the real desktop) before returning; the parent must
            # not translate and re-apply it through Playwright/Quartz.
            continue
        try:
            effective_actions = [
                _effective_action(runtime, item) for item in action_batch
            ]
            effective_action = _effective_action(runtime, action)
            for when, apply in (("before", False), ("after", True)):
                if apply:
                    receipt = _apply_action_batch(
                        runtime,
                        effective_actions,
                        session_id=session_id,
                        frame_id=captured_frame_id,
                        batch_id=f"{session_id}:{phase_dir.name}:{step}",
                        width=width,
                        height=height,
                    )
                    if not receipt.accepted:
                        raise RuntimeError(
                            f"runtime rejected input batch {receipt.batch_id}: "
                            f"{receipt.error or 'unknown error'}"
                        )
                    actions[-1]["execution_receipt"] = asdict(receipt)
                probe_ms = record_public_transition_action(
                    runtime, effective_action, when=when
                )
                if isinstance(probe_ms, (int, float)) and not isinstance(
                    probe_ms, bool
                ):
                    hidden_grader_ms += max(0.0, float(probe_ms))
        except Exception as error:
            infra = _is_infrastructure_error(error)
            actions.append(
                {
                    "step": step,
                    "apply_error": run_context.safe_error_text(
                        str(error), limit=1000
                    ),
                    "infrastructure_error": infra,
                }
            )
            phase_incomplete = phase_incomplete or infra
            break
    # Even done/fail follows a potentially long remote policy request. Dynamic
    # games may advance without an explicit action, so the pre-request step frame
    # is not a safe terminal boundary for hybrid visual+semantic grading.
    raise_if_task_timed_out()
    final_capture_started = time.perf_counter()
    final_capture = _capture_fresh_runtime(
        runtime, phase_dir / "final.png", native_exec_enabled=native_exec_enabled
    )
    fresh_final_shot = final_capture.screenshot
    final_capture_failed = fresh_final_shot is None
    # Keep the prior frame only as diagnostic evidence.  It must never make a
    # failed fresh terminal capture appear gradeable.
    final_shot = fresh_final_shot or last_shot
    if final_capture_failed:
        actions.append(
            {
                "step": len(actions) + 1,
                "error": "final_screenshot_capture_failed",
                "infrastructure_error": True,
                "diagnostic_screenshot": last_shot,
                "capture_attempts": final_capture.attempts,
                "capture_errors": final_capture.capture_errors,
            }
        )
    elif final_capture.capture_errors:
        actions.append(
            {
                "step": len(actions) + 1,
                "capture": "terminal",
                "capture_status": "recovered",
                "capture_attempts": final_capture.attempts,
                "capture_errors": final_capture.capture_errors,
            }
        )
    hidden_grader_ms += (time.perf_counter() - final_capture_started) * 1000
    phase_wall_ms = (time.perf_counter() - phase_start) * 1000
    return PhaseResult(
        reached=False,
        steps=sum(1 for item in actions if "kind" in item),
        screenshot=final_shot,
        actions=actions,
        elapsed_ms=max(0, int(phase_wall_ms - hidden_grader_ms)),
        grader_ms=hidden_grader_ms,
        incomplete=phase_incomplete or final_capture_failed,
    )


def _call_policy_next_action(client: Any, **kwargs: Any) -> Any:
    callable_obj = client.next_action
    try:
        signature = inspect.signature(callable_obj)
    except Exception:
        signature = None
    if signature is None or any(
        param.kind == inspect.Parameter.VAR_KEYWORD for param in signature.parameters.values()
    ):
        return callable_obj(**kwargs)
    supported = {key: value for key, value in kwargs.items() if key in signature.parameters}
    return callable_obj(**supported)


def _is_infrastructure_error(error: Exception) -> bool:
    if run_context.provider_capacity_failure(error) is not None:
        return False
    explicit = getattr(error, "infrastructure_error", None)
    if isinstance(explicit, bool):
        return explicit
    if getattr(error, "usage_accounting_complete", True) is False:
        return True
    status = getattr(error, "status_code", None) or getattr(error, "status", None)
    if isinstance(status, int) and 400 <= status <= 599:
        return True
    name = type(error).__name__.lower()
    text = str(error).lower()
    return any(
        marker in name or marker in text
        for marker in (
            "connection",
            "timeout",
            "rate limit",
            "ratelimit",
            "quota",
            "llm api",
            "llm request rejected",
            "api key",
            "authentication",
            "unauthorized",
            "forbidden",
            "target closed",
            "browser has been closed",
            "page, context or browser has been closed",
            "native input",
            "temporarily unavailable",
            "gateway unavailable",
            "service unavailable",
        )
    )


def _gui_attempt_cost(
    result: dict[str, Any],
    task_cost: dict[str, Any],
    *,
    start_mode: str,
    prior_attributed_burdens: set[tuple[str, str]] | None = None,
) -> dict[str, Any]:
    prior_burdens = set(prior_attributed_burdens or ())
    synthesis_cost = result.get("self_synthesis_cost")
    cache_evidence = result.get("self_synthesis_cache")
    cache_evidence = cache_evidence if isinstance(cache_evidence, dict) else {}
    raw_fingerprint = cache_evidence.get("cache_key_fingerprint")
    fingerprint = str(raw_fingerprint) if raw_fingerprint else None
    cache_hit = bool(cache_evidence.get("cache_hit", False))
    outcome_status = str(result.get("self_synthesis_outcome_status") or "")
    # Provider/transport failures are operational spend, not a counterfactual
    # synthesis burden. Keep them in the actual/transient ledgers, but exclude
    # them from the arm-comparison cost so resumable outages cannot penalize the
    # B/D arm that happened to run first.
    chargeable = bool(
        start_mode in {"synthesized", "restored"}
        and isinstance(synthesis_cost, dict)
        and outcome_status != "infrastructure_error"
    )
    burden_fingerprint = _canonical_hash(
        {
            "cache_key_fingerprint": fingerprint,
            "checkpoint_synthesis_ms": int(
                result.get("checkpoint_synthesis_ms", 0) or 0
            ),
            "outcome_status": outcome_status,
            "synthesis_cost": synthesis_cost if isinstance(synthesis_cost, dict) else None,
        },
        length=32,
    )
    actual_incurred = bool(
        isinstance(synthesis_cost, dict)
        and not cache_hit
        and int(synthesis_cost.get("llm_calls", 0) or 0) > 0
    )
    same_burden_already_attributed = bool(
        chargeable
        and cache_hit
        and fingerprint is not None
        and (fingerprint, burden_fingerprint) in prior_burdens
    )
    # A chargeable cache miss is a new counterfactual burden. Infrastructure
    # misses are deliberately actual-only above; a cache hit for the exact prior
    # chargeable fingerprint is the same burden and is deduplicated on resume.
    charge_this_attempt = bool(
        chargeable and not same_burden_already_attributed
    )
    empty_cost = cost.CostMeter().summary()
    actual_cost = (
        dict(synthesis_cost)
        if actual_incurred and isinstance(synthesis_cost, dict)
        else empty_cost
    )
    transient_actual_cost = (
        dict(synthesis_cost)
        if actual_incurred
        and outcome_status == "infrastructure_error"
        and isinstance(synthesis_cost, dict)
        else cost.CostMeter().summary()
    )
    attributed_cost = (
        dict(synthesis_cost)
        if charge_this_attempt and isinstance(synthesis_cost, dict)
        else cost.CostMeter().summary()
    )
    if outcome_status == "infrastructure_error" and actual_incurred:
        reason = "infrastructure_overhead_actual_only"
    elif not chargeable:
        reason = "not_attributable"
    elif same_burden_already_attributed:
        reason = "same_fingerprint_cache_hit_already_attributed"
    elif cache_hit:
        reason = "cache_hit_counterfactual_attribution"
    elif actual_incurred:
        reason = "cache_miss_actual_incurred"
    else:
        reason = "cache_miss_zero_call_burden"
    accounting = {
        "cache_key_fingerprint": fingerprint,
        "counterfactual_burden_fingerprint": burden_fingerprint,
        "cache_hit": cache_hit,
        "counterfactual_attributable": chargeable,
        "actual_incurred": actual_incurred,
        "actual_cost": actual_cost,
        "transient_actual_cost": transient_actual_cost,
        "attributed": charge_this_attempt,
        "attributed_cost": attributed_cost,
        "deduplicated": same_burden_already_attributed,
        "reason": reason,
    }
    result["synthesis_cache_fingerprint"] = fingerprint
    result["synthesis_cache_hit"] = cache_hit
    result["synthesis_actual_incurred_this_attempt"] = actual_incurred
    result["synthesis_cost_charged_this_attempt"] = charge_this_attempt
    result["synthesis_cost_charged"] = bool(
        (
            fingerprint is not None
            and (fingerprint, burden_fingerprint) in prior_burdens
        )
        or charge_this_attempt
    )
    attempt_cost = cost.merge_summaries([attributed_cost, task_cost])
    attempt_cost["task_actual_cost"] = dict(task_cost)
    attempt_cost["synthesis_accounting"] = accounting
    return attempt_cost


def _attempt_hash_payload(
    attempt: dict[str, Any], *, task_id: str
) -> dict[str, Any]:
    """Return the canonical, task-bound payload for one paid attempt."""

    return {
        "task_id": str(task_id),
        "attempt_ordinal": attempt.get("attempt_ordinal"),
        "attempt_status": attempt.get("attempt_status"),
        "retry_category": attempt.get("retry_category"),
        "retry_reason": attempt.get("retry_reason"),
        "previous_attempt_hash": attempt.get("previous_attempt_hash"),
        "task_actual_cost": attempt.get("task_actual_cost"),
        "synthesis_accounting": attempt.get("synthesis_accounting"),
    }


def _sha256_json(value: Any) -> str:
    encoded = json.dumps(
        value,
        sort_keys=True,
        separators=(",", ":"),
        ensure_ascii=False,
    ).encode("utf-8")
    return hashlib.sha256(encoded).hexdigest()


def _bind_attempt_ledger(
    attempts: list[dict[str, Any]], *, task_id: str
) -> tuple[list[dict[str, Any]], str]:
    """Build a full SHA-256 hash chain over a task's ordered attempts."""

    bound: list[dict[str, Any]] = []
    previous_hash: str | None = None
    for ordinal, raw_attempt in enumerate(attempts, start=1):
        attempt = dict(raw_attempt)
        attempt["attempt_ordinal"] = ordinal
        attempt["previous_attempt_hash"] = previous_hash
        attempt["attempt_hash"] = _sha256_json(
            _attempt_hash_payload(attempt, task_id=task_id)
        )
        previous_hash = attempt["attempt_hash"]
        bound.append(attempt)
    ledger_hash = _sha256_json(
        {
            "task_id": str(task_id),
            "attempt_hashes": [attempt["attempt_hash"] for attempt in bound],
        }
    )
    return bound, ledger_hash


def _validated_attempt_ledger(
    result: dict[str, Any], *, task_id: str, incomplete: bool
) -> list[dict[str, Any]]:
    """Fail closed when resume evidence is not the exact persisted hash chain."""

    raw_attempts = result.get("attempt_costs")
    if not isinstance(raw_attempts, list) or not raw_attempts:
        raise cost.UsageAccountingError(
            f"cannot safely resume {task_id}: missing hash-bound attempt_costs"
        )
    attempts = [dict(value) for value in raw_attempts if isinstance(value, dict)]
    if len(attempts) != len(raw_attempts):
        raise cost.UsageAccountingError(
            f"cannot safely resume {task_id}: malformed attempt_costs"
        )
    if int(result.get("attempt_count", 0) or 0) != len(attempts):
        raise cost.UsageAccountingError(
            f"cannot safely resume {task_id}: attempt_count mismatch"
        )
    rebound, ledger_hash = _bind_attempt_ledger(attempts, task_id=task_id)
    for index, (original, expected) in enumerate(
        zip(attempts, rebound, strict=True)
    ):
        if original.get("attempt_ordinal") != expected["attempt_ordinal"]:
            raise cost.UsageAccountingError(
                f"cannot safely resume {task_id}: attempt ordinal mismatch"
            )
        if index < len(attempts) - 1:
            expected_status = "retryable_infrastructure"
        elif not incomplete:
            expected_status = "treatment"
        elif result.get("retryable_incomplete") is True:
            expected_status = "retryable_infrastructure"
        elif cost.contains_unknown_usage(result):
            expected_status = "unknown_usage"
        else:
            expected_status = "nonretryable_incomplete"
        if original.get("attempt_status") != expected_status:
            raise cost.UsageAccountingError(
                f"cannot safely resume {task_id}: invalid prior attempt status"
            )
        retry_category = original.get("retry_category")
        retry_reason = original.get("retry_reason")
        if expected_status == "retryable_infrastructure":
            if retry_category not in {"infra", "rate_limit"}:
                raise cost.UsageAccountingError(
                    f"cannot safely resume {task_id}: invalid retry category"
                )
            if not isinstance(retry_reason, str) or not retry_reason.strip():
                raise cost.UsageAccountingError(
                    f"cannot safely resume {task_id}: missing retry reason"
                )
            if (
                run_context.error_category(RuntimeError(retry_reason))
                != retry_category
            ):
                raise cost.UsageAccountingError(
                    f"cannot safely resume {task_id}: retry reason/category mismatch"
                )
        elif retry_category is not None or retry_reason is not None:
            raise cost.UsageAccountingError(
                f"cannot safely resume {task_id}: terminal attempt has retry metadata"
            )
        if original.get("previous_attempt_hash") != expected["previous_attempt_hash"]:
            raise cost.UsageAccountingError(
                f"cannot safely resume {task_id}: attempt hash chain mismatch"
            )
        if original.get("attempt_hash") != expected["attempt_hash"]:
            raise cost.UsageAccountingError(
                f"cannot safely resume {task_id}: attempt hash mismatch"
            )
        if not isinstance(original.get("task_actual_cost"), dict):
            raise cost.UsageAccountingError(
                f"cannot safely resume {task_id}: missing task_actual_cost"
            )
    if result.get("attempt_ledger_hash") != ledger_hash:
        raise cost.UsageAccountingError(
            f"cannot safely resume {task_id}: attempt ledger hash mismatch"
        )
    return attempts


def _attributed_synthesis_fingerprints(
    attempts: list[dict[str, Any]],
) -> set[str]:
    fingerprints: set[str] = set()
    for attempt in attempts:
        accounting = attempt.get("synthesis_accounting")
        if not isinstance(accounting, dict) or not accounting.get("attributed"):
            continue
        fingerprint = accounting.get("cache_key_fingerprint")
        if fingerprint:
            fingerprints.add(str(fingerprint))
    return fingerprints


def _attributed_synthesis_burdens(
    attempts: list[dict[str, Any]],
) -> set[tuple[str, str]]:
    burdens: set[tuple[str, str]] = set()
    for attempt in attempts:
        accounting = attempt.get("synthesis_accounting")
        if not isinstance(accounting, dict) or not accounting.get("attributed"):
            continue
        fingerprint = accounting.get("cache_key_fingerprint")
        burden = accounting.get("counterfactual_burden_fingerprint")
        if fingerprint and burden:
            burdens.add((str(fingerprint), str(burden)))
    return burdens


def _merged_attempt_synthesis_cost(
    attempts: list[dict[str, Any]],
    field: str,
) -> dict[str, Any]:
    summaries: list[dict[str, Any]] = []
    for attempt in attempts:
        accounting = attempt.get("synthesis_accounting")
        value = accounting.get(field) if isinstance(accounting, dict) else None
        if isinstance(value, dict):
            summaries.append(value)
    return cost.merge_summaries(summaries)


def _build_step_budgets(
    max_steps: int,
    step_budgets: dict[str, int] | None,
) -> dict[str, int]:
    """Resolve horizon overrides without leaking formal-C1 defaults.

    ``max_steps`` remains the public default for standalone/non-formal callers.
    Formal C1 passes its uniform mapping explicitly through ``step_budgets``.
    """

    budgets = {horizon: int(max_steps) for horizon in C1_HORIZON_CLASSES}
    if step_budgets:
        budgets.update({str(key): int(value) for key, value in step_budgets.items()})
    return budgets


def _resolve_step_budget(
    task: Any,
    budgets: dict[str, int],
    *,
    default_steps: int,
) -> int:
    """Return one task's decision-step budget.

    Explicit horizon overrides win; otherwise the caller's public ``max_steps``
    value remains authoritative.
    """

    horizon = str(getattr(task, "horizon_class", "") or "").lower()
    if horizon in budgets:
        return int(budgets[horizon])
    return int(default_steps)


def _resolve_task_timeout_s(task: Any, default_timeout_s: float) -> float:
    """Return one task's wall-clock deadline, preferring its published budget."""

    budget_ms = c1_task_budget_ms(
        task, default_ms=int(round(float(default_timeout_s) * 1000.0))
    )
    return validate_task_timeout_s(budget_ms / 1000.0)


