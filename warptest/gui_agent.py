def _unity_semantic_grade(
    runtime: UnityC1Session,
    oracle_spec: dict[str, Any],
    *,
    after: bool,
) -> tuple[bool, str, dict[str, Any]]:
    """Read live Unity state without exposing the probe to the policy."""

    try:
        report = (
            runtime.semantic_goal(oracle_spec)
            if after
            else runtime.semantic_start(oracle_spec)
        )
    except Exception as error:
        return False, "validate_error", {"error": str(error)}
    if not isinstance(report, dict):
        return False, "validate_error", {
            "error": "Unity semantic probe returned a non-object report"
        }
    checks = report.get("checks")
    rows = checks if isinstance(checks, list) else []
    source = str(report.get("source") or report.get("semantic_source") or "")
    expected_source = f"{runtime.benchmark}_live_semantic_probe_v1"
    rows_well_formed = bool(
        rows
        and all(
            isinstance(row, dict) and row.get("status") in {"success", "failure"}
            for row in rows
        )
    )
    checks_ok = bool(
        rows_well_formed
        and all(row.get("status") == "success" for row in rows)
    )
    status = str(report.get("status") or "")
    expected_ok = bool(status == "success" and checks_ok)
    status_matches_checks = bool(
        (status == "success" and checks_ok)
        or (status == "failure" and not checks_ok)
    )
    malformed = bool(
        report.get("live") is not True
        or source != expected_source
        or status not in {"success", "failure"}
        or not rows_well_formed
        or not status_matches_checks
        or not isinstance(report.get("ok"), bool)
        or report.get("ok") is not expected_ok
        or report.get("transition_evidence_valid") is not True
    )
    ok = bool(not malformed and expected_ok)
    semantic_status = "validate_error" if malformed else status
    return ok, semantic_status, {
        "source": source,
        "live": report.get("live") is True,
        "detail": report.get("detail"),
        "checks": rows,
        "transition_evidence": report.get("transition_evidence"),
        "transition_evidence_valid": report.get("transition_evidence_valid"),
        **(
            {
                "error": (
                    "Unity semantic report failed live provenance or internal "
                    "consistency validation"
                )
            }
            if malformed
            else {}
        ),
    }


def _optional_unity_proof(
    result: dict[str, Any],
    runtime: UnityC1Session,
    path: Path,
    *,
    stage: str,
) -> None:
    """Record a clean camera-frame proof without replacing desktop policy pixels."""

    try:
        result[f"unity_{stage}_proof_screenshot"] = runtime.unity_screenshot(path)
    except Exception as error:
        result[f"unity_{stage}_proof_error"] = run_context.safe_error_text(
            error, limit=500
        )


def _run_unity_c1_agent_task(
    base: Path,
    task: StateLoopTask,
    *,
    model: str,
    base_url: str,
    api_key: str,
    api_key_env: str,
    synth_model: str,
    max_explore_steps: int,
    temperature: float,
    out_dir: Path,
    max_steps: int,
    headless: bool,
    start_mode: str,
    policy_kind: str,
    policy_client: Any | None,
    observer: FixedVisualBridge | None,
    seed: int,
    shared_synthesis_cache: Path | None = None,
) -> dict[str, Any]:
    """Run Agent-S against one real background jynew or PAL3 Unity process."""

    task_dir = out_dir / "tasks" / task.id
    synthesized = start_mode in {"synthesized", "restored"}
    result = _new_gui_result(
        task,
        start_mode="synthesized" if synthesized else "from_start",
        policy_kind=policy_kind,
        model=model,
        seed=int(seed),
        max_steps=max_steps,
    )
    if policy_kind not in {"agent_s", "scalecua"}:
        result.update(
            status="unsupported",
            incomplete=True,
            reason="jynew/PAL3 C1 requires a background-pixel GUI policy",
        )
        return result
    # The invocation-wide ``headless`` flag controls browser presentation.
    # Unity still runs its private background GameView and must not require a
    # frontmost editor window when the flag is true.

    try:
        repo = resolve_task_repo(base, task.issue)
        oracle_spec_path = (base / task.oracle_spec).resolve()
        oracle_spec = _seed_spec(
            load_spec(oracle_spec_path), seed, benchmark=task.benchmark
        )
    except Exception as error:
        result.update(
            status="failed", incomplete=True, reason=f"task setup failed: {error}"
        )
        return result
    result["validity_class"] = str(
        (oracle_spec.get("checkpoint") or {}).get("expected_validity")
        or "unclassified"
    )
    if not _attach_reference_replay_audit(
        result,
        base=base,
        task=task,
        repo=repo,
        oracle_spec=oracle_spec,
        oracle_spec_path=oracle_spec_path,
        seed=int(seed),
        headless=False,
    ):
        return result

    generated_spec: dict[str, Any] | None = None
    synth_spec_path: Path | None = None
    checkpoint_synthesis_ms = 0
    if synthesized:
        synthesis = _obtain_self_synthesis(
            task,
            base=base,
            seed=int(seed),
            synth_model=synth_model,
            base_url=base_url,
            api_key_env=api_key_env,
            temperature=temperature,
            max_explore_steps=max_explore_steps,
            artifact_dir=task_dir / "synthesis-artifacts",
            policy_kind=policy_kind,
            shared_cache_root=shared_synthesis_cache,
        )
        generated_spec = _apply_self_synthesis_result(
            result, synthesis, task, seed=int(seed)
        )
        if generated_spec is None:
            return result
        checkpoint_synthesis_ms = int(result.get("checkpoint_synthesis_ms", 0) or 0)
        synth_spec_path = task_dir / "synth-spec.yaml"
        synth_spec_path.parent.mkdir(parents=True, exist_ok=True)
        synth_spec_path.write_text(
            yaml.safe_dump(generated_spec, sort_keys=False, allow_unicode=False),
            encoding="utf-8",
        )
        result["synthesized_spec"] = str(synth_spec_path)
        _apply_start_contract(
            result,
            task,
            seed=int(seed),
            start_mode="synthesized",
            generated_spec=generated_spec,
        )

    grader_accum_ms = 0
    golden_started = time.perf_counter()
    try:
        goldens = lookup_cached_oracle_goldens(repo, oracle_spec)
        if goldens is None:
            # Unity is a background protocol. The enclosing task lease is scoped
            # to its canonical (or cloned) project path, so unrelated projects do
            # not contend on the foreground keyboard/mouse lock.
            with contextlib.nullcontext():
                goldens = _ensure_unity_checkpoint_goldens(
                    repo,
                    oracle_spec,
                    oracle_spec_path,
                    task_dir / "goldens",
                    benchmark=task.benchmark,
                    headless=False,
                )
        result["oracle_goldens"] = _oracle_goldens_payload(goldens)
    except StateManagementUnsupported as error:
        result.update(
            status="unsupported",
            incomplete=True,
            reason=f"Unity oracle golden generation unsupported: {error}",
        )
        return result
    except Exception as error:
        result.update(
            status="failed",
            incomplete=True,
            infrastructure_error=_is_infrastructure_error(error),
            reason=f"Unity oracle golden generation failed: {error}",
        )
        return result
    grader_accum_ms += int((time.perf_counter() - golden_started) * 1000)

    phase_a = PhaseResult(False, 0, None, elapsed_ms=0)
    phase_b = PhaseResult(False, 0, None, elapsed_ms=0)
    verdict: dict[str, Any] | None = None
    before_semantic_ok = False
    after_semantic_ok = False
    before_semantic_status = "not_run"
    after_semantic_status = "not_run"
    before_semantic_detail: dict[str, Any] = {}
    after_semantic_detail: dict[str, Any] = {}
    initial_shot: str | None = None
    before_shot: str | None = None
    after_shot: str | None = None
    runtime_bootstrap_ms = 0
    checkpoint_restore_ms = 0
    initial_seed: dict[str, Any] | None = None

    with contextlib.nullcontext():
        boot_started = time.perf_counter()
        try:
            with create_c1_unity_session(
                task.benchmark,
                repo,
                task_dir / "agent",
                experiment_seed=int(seed),
            ) as runtime:
                # Record the launched process before any protocol/calibration work so
                # an early runtime failure cannot masquerade as pre-launch failure.
                initial_seed = _record_unity_seed_evidence(result, runtime)
                clean = runtime.clean_entry()
                if clean.get("status") != "success" or clean.get(
                    "actions_executed"
                ) is not False:
                    raise RuntimeError(f"Unity clean entry failed closed: {clean}")
                runtime_bootstrap_ms = int(
                    (time.perf_counter() - boot_started) * 1000
                )
                result["runtime_bootstrap_ms"] = runtime_bootstrap_ms
                if runtime.hold_pid is None:
                    raise RuntimeError("Unity background runtime PID is unavailable")
                result["calibration"] = {
                    "passed": True,
                    **runtime.calibration_metadata(),
                    "backend": "unity_background_pixel_v1",
                }
                initial_shot = runtime.screenshot(task_dir / "initial.png")
                client = policy_client or GuiAgentClient(
                    model=model,
                    base_url=base_url,
                    api_key=api_key,
                    api_key_env=api_key_env,
                    temperature=temperature,
                )

                if generated_spec is not None:
                    restore_started = time.perf_counter()
                    restore = runtime.restore_target_only(
                        generated_spec, synth_spec_path
                    )
                    checkpoint_restore_ms = int(
                        (time.perf_counter() - restore_started) * 1000
                    )
                    result["checkpoint_restore_ms"] = checkpoint_restore_ms
                    result["restore_status"] = restore.get("status")
                    result["restore_actions_executed"] = restore.get(
                        "actions_executed"
                    )
                    if (
                        restore.get("status") != "success"
                        or restore.get("phase") != "target_only"
                        or restore.get("actions_executed") is not False
                    ):
                        _record_unity_seed_evidence(
                            result, runtime, initial=initial_seed
                        )
                        _mark_start_construction_fair_failure(
                            result, StartConstructionStatus.RESTORE_FAILED
                        )
                        result.update(
                            status="failure",
                            incomplete=False,
                            reason=(
                                "self-synthesized Unity start did not restore "
                                f"target-only: {restore}"
                            ),
                        )
                        return result
                    _set_start_construction_status(
                        result, StartConstructionStatus.REACHED
                    )
                    before_shot = runtime.screenshot(
                        task_dir / "synth-start.png"
                    )
                    phase_a = PhaseResult(
                        reached=True,
                        steps=0,
                        screenshot=before_shot,
                        elapsed_ms=0,
                    )
                else:
                    result["policy_phase_started"] = True
                    phase_a = _run_phase(
                        runtime=runtime,
                        client=client,
                        phase_dir=task_dir / "phase-a",
                        instruction=(
                            f"Satisfy these preconditions: {_task_preconditions(task)}. "
                            "Use only the visible game UI, then emit done."
                        ),
                        max_steps=max_steps,
                        observer=observer,
                        task_id=task.id,
                    )
                    before_shot = phase_a.screenshot
                grader_accum_ms += int(phase_a.grader_ms)
                if phase_a.incomplete:
                    _record_unity_seed_evidence(result, runtime)
                    return _abort_incomplete_phase(
                        result,
                        phase_name="phase_a",
                        phase_a=phase_a,
                        phase_b=None,
                        time_to_start_ms=phase_a.elapsed_ms,
                        checkpoint_synthesis_ms=checkpoint_synthesis_ms,
                        checkpoint_restore_ms=checkpoint_restore_ms,
                        runtime_bootstrap_ms=runtime_bootstrap_ms,
                        grader_ms=int(grader_accum_ms),
                        initial_shot=initial_shot,
                        before_shot=before_shot,
                    )
                if not before_shot:
                    raise RuntimeError("Unity start boundary screenshot is unavailable")

                result["start_grading_started"] = True
                semantic_started = time.perf_counter()
                (
                    before_semantic_ok,
                    before_semantic_status,
                    before_semantic_detail,
                ) = _unity_semantic_grade(runtime, oracle_spec, after=False)
                grader_accum_ms += int(
                    (time.perf_counter() - semantic_started) * 1000
                )
                initial_seed = _record_unity_seed_evidence(result, runtime)
                _optional_unity_proof(
                    result,
                    runtime,
                    task_dir / "unity-start-proof.png",
                    stage="start",
                )
                time_to_start_ms = (
                    checkpoint_restore_ms if synthesized else phase_a.elapsed_ms
                )
                start_initial_shot = before_shot if synthesized else initial_shot
                if not before_semantic_ok:
                    _record_unity_seed_evidence(
                        result, runtime, initial=initial_seed
                    )
                    return _finish_start_gate_failure(
                        result,
                        phase_a=phase_a,
                        before_shot=before_shot,
                        initial_shot=start_initial_shot,
                        before_semantic_ok=False,
                        before_semantic_status=before_semantic_status,
                        before_semantic_detail=before_semantic_detail,
                        before_verdict=None,
                        time_to_start_ms=time_to_start_ms,
                        checkpoint_synthesis_ms=checkpoint_synthesis_ms,
                        checkpoint_restore_ms=checkpoint_restore_ms,
                        runtime_bootstrap_ms=runtime_bootstrap_ms,
                        grader_ms=int(grader_accum_ms),
                    )

                result["visual_grading_started"] = True
                visual_started = time.perf_counter()
                verdict, runtime_hold = _run_before_visual_gate(
                    runtime=runtime,
                    before_shot=str(before_shot),
                    goldens=goldens,
                    task=task,
                    result=result,
                )
                grader_accum_ms += int(
                    (time.perf_counter() - visual_started) * 1000
                )
                result["start_grading_runtime_hold"] = runtime_hold
                before_visual_ok, _ = _verdict_flags(verdict)
                if not before_visual_ok:
                    _record_unity_seed_evidence(
                        result, runtime, initial=initial_seed
                    )
                    return _finish_start_gate_failure(
                        result,
                        phase_a=phase_a,
                        before_shot=before_shot,
                        initial_shot=start_initial_shot,
                        before_semantic_ok=True,
                        before_semantic_status=before_semantic_status,
                        before_semantic_detail=before_semantic_detail,
                        before_verdict=verdict,
                        time_to_start_ms=time_to_start_ms,
                        checkpoint_synthesis_ms=checkpoint_synthesis_ms,
                        checkpoint_restore_ms=checkpoint_restore_ms,
                        runtime_bootstrap_ms=runtime_bootstrap_ms,
                        grader_ms=int(grader_accum_ms),
                    )
                result["start_gate_status"] = "passed"
                result["before_visual_status"] = "evaluated"

                remaining = (
                    max_steps
                    if synthesized
                    else max(0, max_steps - phase_a.steps)
                )
                if remaining:
                    result["policy_phase_started"] = True
                    phase_b = _run_phase(
                        runtime=runtime,
                        client=client,
                        phase_dir=task_dir / "phase-b",
                        instruction=_public_phase_b_instruction(
                            task,
                            environment_instruction=(
                                "Use only the visible game UI."
                            ),
                        ),
                        max_steps=remaining,
                        observer=observer,
                        task_id=task.id,
                    )
                else:
                    phase_b = PhaseResult(
                        reached=False,
                        steps=0,
                        screenshot=before_shot,
                        elapsed_ms=0,
                    )
                after_shot = phase_b.screenshot
                grader_accum_ms += int(phase_b.grader_ms)
                if phase_b.incomplete:
                    _record_unity_seed_evidence(
                        result, runtime, initial=initial_seed
                    )
                    return _abort_incomplete_phase(
                        result,
                        phase_name="phase_b",
                        phase_a=phase_a,
                        phase_b=phase_b,
                        time_to_start_ms=time_to_start_ms,
                        checkpoint_synthesis_ms=checkpoint_synthesis_ms,
                        checkpoint_restore_ms=checkpoint_restore_ms,
                        runtime_bootstrap_ms=runtime_bootstrap_ms,
                        grader_ms=int(grader_accum_ms),
                        initial_shot=start_initial_shot,
                        before_shot=before_shot,
                        before_semantic_ok=before_semantic_ok,
                        before_semantic_status=before_semantic_status,
                        before_semantic_detail=before_semantic_detail,
                        before_verdict=verdict,
                    )

                semantic_started = time.perf_counter()
                (
                    after_semantic_ok,
                    after_semantic_status,
                    after_semantic_detail,
                ) = _unity_semantic_grade(runtime, oracle_spec, after=True)
                grader_accum_ms += int(
                    (time.perf_counter() - semantic_started) * 1000
                )
                _record_unity_seed_evidence(
                    result, runtime, initial=initial_seed
                )
                _optional_unity_proof(
                    result,
                    runtime,
                    task_dir / "unity-goal-proof.png",
                    stage="goal",
                )
        except Exception as error:
            result.update(
                status="failed",
                incomplete=True,
                reason=f"Unity C1 GUI runtime failed: {error}",
            )
            return result

    grader_started = time.perf_counter()
    if (
        verdict is not None
        and before_shot
        and after_shot
        and Path(before_shot).exists()
        and Path(after_shot).exists()
    ):
        verdict = _run_after_visual_grade(
            before_verdict=verdict,
            before_shot=before_shot,
            after_shot=after_shot,
            goldens=goldens,
            task=task,
        )
    before_visual_ok, after_visual_ok = _verdict_flags(verdict)
    grader_ms = int(
        grader_accum_ms + (time.perf_counter() - grader_started) * 1000
    )
    start_success = bool(before_visual_ok and before_semantic_ok)
    goal_success = bool(after_visual_ok and after_semantic_ok)
    e2e_success = bool(start_success and goal_success)
    incomplete = bool(
        not _verdict_is_complete(verdict)
        or phase_a.incomplete
        or phase_b.incomplete
        or before_semantic_status in {"not_run", "validate_error"}
        or after_semantic_status in {"not_run", "validate_error"}
    )
    test_ms = int(phase_a.elapsed_ms + phase_b.elapsed_ms)
    excluding_ms = int(checkpoint_restore_ms + test_ms)
    including_ms = int(checkpoint_synthesis_ms + excluding_ms)
    result.update(
        {
            "result": e2e_success,
            "status": (
                "incomplete"
                if incomplete
                else ("success" if e2e_success else "failure")
            ),
            "incomplete": incomplete,
            "before_visual_ok": bool(before_visual_ok),
            "before_semantic_ok": bool(before_semantic_ok),
            "after_visual_ok": bool(after_visual_ok),
            "after_semantic_ok": bool(after_semantic_ok),
            "start_success": start_success,
            "goal_success": goal_success,
            "e2e_success": e2e_success,
            "before_ok": bool(before_visual_ok),
            "semantic_ok": bool(after_semantic_ok),
            "stage2_pass": goal_success,
            "stage2_visual_pass": bool(after_visual_ok),
            "e2e_pass": e2e_success,
            "visual_only_upper_bound": bool(
                before_visual_ok and after_visual_ok
            ),
            "visual_only_evaluation_status": "evaluated",
            "start_gate_status": "passed",
            "goal_evaluation_status": "evaluated",
            "before_visual_status": "evaluated",
            "after_visual_status": "evaluated",
            "before_semantic_status": before_semantic_status,
            "before_semantic_detail": before_semantic_detail,
            "after_semantic_status": after_semantic_status,
            "after_semantic_detail": after_semantic_detail,
            "semantic_status": after_semantic_status,
            "semantic_detail": after_semantic_detail,
            "semantic_probe_source": before_semantic_detail.get("source"),
            "policy_action_interface": "pixel_mouse_keyboard_only",
            "policy_received_semantic_probe": False,
            "policy_observation_source": "application_framebuffer_pixels",
            "scripted_transition_executed": False,
            "time_to_start_ms": (
                checkpoint_restore_ms if synthesized else phase_a.elapsed_ms
            ),
            "time_start_to_goal_ms": phase_b.elapsed_ms,
            "time_e2e_excluding_synthesis_ms": excluding_ms,
            "time_e2e_including_synthesis_ms": including_ms,
            "termination_time_ms": including_ms,
            "checkpoint_synthesis_ms": checkpoint_synthesis_ms,
            "checkpoint_restore_ms": checkpoint_restore_ms,
            "runtime_bootstrap_ms": runtime_bootstrap_ms,
            "grader_ms": grader_ms,
            "wall_ms": test_ms,
            "steps": {
                "phase_a": phase_a.steps,
                "phase_b": phase_b.steps,
                "total": phase_a.steps + phase_b.steps,
            },
            "decision_budget": max_steps,
            "budget_exhausted": phase_a.steps + phase_b.steps >= max_steps,
            "initial_state_screenshot_hash": _screenshot_fingerprint(
                before_shot if synthesized else initial_shot
            ),
            "screenshot_before": before_shot,
            "screenshot_after": after_shot,
            "pair_verdict": verdict,
            "phase_a_actions": phase_a.actions,
            "phase_b_actions": phase_b.actions,
        }
    )
    return result


def _run_openra_settings_agent_task(
    base: Path,
    task: StateLoopTask,
    *,
    model: str,
    base_url: str,
    api_key: str,
    api_key_env: str,
    synth_model: str,
    max_explore_steps: int,
    temperature: float,
    out_dir: Path,
    max_steps: int,
    start_mode: str,
    policy_kind: str,
    policy_client: Any | None,
    observer: FixedVisualBridge | None,
    seed: int,
    shared_synthesis_cache: Path | None = None,
) -> dict[str, Any]:
    """Run C/D against a real OpenRA Settings UI and public settings file."""

    task_dir = out_dir / "tasks" / task.id
    synthesized = start_mode in {"synthesized", "restored"}
    result = _new_gui_result(
        task,
        start_mode="synthesized" if synthesized else "from_start",
        policy_kind=policy_kind,
        model=model,
        seed=int(seed),
        max_steps=max_steps,
    )
    if policy_kind not in {"agent_s", "scalecua"}:
        result.update(
            status="unsupported",
            incomplete=True,
            reason="OpenRA C1 native settings tasks require a background-pixel policy",
        )
        return result
    try:
        repo = resolve_task_repo(base, task.issue)
        oracle_spec_path = (base / task.oracle_spec).resolve()
        oracle_spec = _seed_spec(
            load_spec(oracle_spec_path), seed, benchmark=task.benchmark
        )
        openra_target = oracle_spec.get("target") or {}
        gameplay_task = (
            isinstance(openra_target, dict)
            and openra_target.get("kind") == "openra_map"
        )
        oracle_start = (
            {}
            if gameplay_task
            else openra_target_settings(oracle_spec)
        )
    except Exception as error:
        result.update(status="failed", incomplete=True, reason=f"task setup failed: {error}")
        return result
    result["validity_class"] = str(
        (oracle_spec.get("checkpoint") or {}).get("expected_validity")
        or "unclassified"
    )
    if not _attach_reference_replay_audit(
        result,
        base=base,
        task=task,
        repo=repo,
        oracle_spec=oracle_spec,
        oracle_spec_path=oracle_spec_path,
        seed=int(seed),
        headless=False,
    ):
        return result

    generated_spec: dict[str, Any] | None = None
    checkpoint_synthesis_ms = 0
    if synthesized:
        synthesis = _obtain_self_synthesis(
            task,
            base=base,
            seed=int(seed),
            synth_model=synth_model,
            base_url=base_url,
            api_key_env=api_key_env,
            temperature=temperature,
            max_explore_steps=max_explore_steps,
            artifact_dir=task_dir / "synthesis-artifacts",
            policy_kind=policy_kind,
            shared_cache_root=shared_synthesis_cache,
        )
        generated_spec = _apply_self_synthesis_result(
            result, synthesis, task, seed=int(seed)
        )
        if generated_spec is None:
            return result
        checkpoint_synthesis_ms = int(result.get("checkpoint_synthesis_ms", 0) or 0)
        synth_path = task_dir / "synth-spec.yaml"
        synth_path.parent.mkdir(parents=True, exist_ok=True)
        synth_path.write_text(
            yaml.safe_dump(generated_spec, sort_keys=False, allow_unicode=False),
            encoding="utf-8",
        )
        result["synthesized_spec"] = str(synth_path)
        try:
            session_settings = (
                {}
                if gameplay_task
                else openra_target_settings(generated_spec)
            )
        except Exception as error:
            _mark_start_construction_fair_failure(
                result, StartConstructionStatus.RESTORE_FAILED
            )
            result.update(
                status="failure",
                incomplete=False,
                reason=f"self-synthesized OpenRA start is invalid: {error}",
                checkpoint_restore_ms=0,
                policy_phase_started=False,
                start_grading_started=False,
                visual_grading_started=False,
            )
            return result
        _apply_start_contract(
            result,
            task,
            seed=int(seed),
            start_mode="synthesized",
            generated_spec=generated_spec,
        )
    else:
        # The registered start fields are engine defaults. Only first-run/network
        # infrastructure is preconfigured; the policy receives no target mutation.
        if gameplay_task:
            session_settings = {}
        else:
            non_default = []
            for section, values in oracle_start.items():
                for key, value in values.items():
                    if key == "IntroductionPromptVersion":
                        continue
                    if OPENRA_DEFAULT_SETTINGS.get(section, {}).get(key) != value:
                        non_default.append(f"{section}.{key}")
            if non_default:
                result.update(
                    status="failed",
                    incomplete=True,
                    reason=(
                        "OpenRA from-start target contains non-default settings: "
                        + ", ".join(non_default)
                    ),
                )
                return result
            session_settings = {
                "Game": {
                    "IntroductionPromptVersion": int(
                        oracle_start.get("Game", {}).get(
                            "IntroductionPromptVersion", 999
                        )
                    )
                }
            }

    grader_accum_ms = 0
    golden_started = time.perf_counter()
    try:
        goldens = lookup_cached_oracle_goldens(repo, oracle_spec)
        if goldens is None:
            goldens = (
                _registered_desktop_state_goldens(
                    repo,
                    oracle_spec,
                    oracle_spec_path,
                    task_dir / "goldens",
                    benchmark="OpenRA",
                )
                if gameplay_task
                else _ensure_openra_settings_goldens(
                    repo,
                    oracle_spec,
                    oracle_spec_path,
                    task_dir / "goldens",
                    seed=int(seed),
                )
            )
        result["oracle_goldens"] = _oracle_goldens_payload(goldens)
    except Exception as error:
        result.update(
            status="failed",
            incomplete=True,
            reason=f"OpenRA oracle golden generation failed: {error}",
        )
        return result
    grader_accum_ms += int((time.perf_counter() - golden_started) * 1000)

    phase_a = PhaseResult(False, 0, None, elapsed_ms=0)
    phase_b = PhaseResult(False, 0, None, elapsed_ms=0)
    verdict: dict[str, Any] | None = None
    before_semantic_ok = False
    after_semantic_ok = False
    before_semantic_status = "not_run"
    after_semantic_status = "not_run"
    before_semantic_detail: dict[str, Any] = {}
    after_semantic_detail: dict[str, Any] = {}
    before_shot: str | None = None
    after_shot: str | None = None
    initial_shot: str | None = None
    runtime_bootstrap_ms = 0
    checkpoint_restore_ms = 0
    initial_seed: dict[str, Any] | None = None

    with contextlib.nullcontext():
        boot_started = time.perf_counter()
        try:
            runtime_context = (
                OpenRAGameplaySession(
                    repo,
                    task_dir / "agent",
                    spec=generated_spec if synthesized and generated_spec else oracle_spec,
                    experiment_seed=int(seed),
                )
                if gameplay_task
                else OpenRASettingsSession(
                    repo,
                    task_dir / "agent",
                    settings=session_settings,
                    experiment_seed=int(seed),
                )
            )
            with runtime_context as runtime:
                runtime_bootstrap_ms = int(
                    (time.perf_counter() - boot_started) * 1000
                )
                result["runtime_bootstrap_ms"] = runtime_bootstrap_ms
                checkpoint_restore_ms = runtime_bootstrap_ms if synthesized else 0
                result["checkpoint_restore_ms"] = checkpoint_restore_ms
                initial_seed = _record_openra_seed_evidence(result, runtime)
                initial_shot = runtime.screenshot(task_dir / "initial.png")
                result["calibration"] = {
                    "passed": True,
                    "execution_backend": BACKGROUND_PIXEL_BACKEND,
                    "capture_backend": "openra_renderer_save_screenshot_sync_v1",
                    "input_backend": "openra_default_input_handler_v1",
                    "coordinate_space": FRAME_PIXEL_COORDINATE_SPACE,
                    "foreground_required": False,
                    "pid": runtime.hold_pid,
                    "frame": {"width": runtime.width, "height": runtime.height},
                }
                client = policy_client or GuiAgentClient(
                    model=model,
                    base_url=base_url,
                    api_key=api_key,
                    api_key_env=api_key_env,
                    temperature=temperature,
                )
                if synthesized:
                    _set_start_construction_status(
                        result, StartConstructionStatus.REACHED
                    )
                    before_shot = initial_shot
                    phase_a = PhaseResult(
                        reached=True,
                        steps=0,
                        screenshot=before_shot,
                        elapsed_ms=0,
                    )
                else:
                    result["policy_phase_started"] = True
                    phase_a = _run_phase(
                        runtime=runtime,
                        client=client,
                        phase_dir=task_dir / "phase-a",
                        instruction=(
                            f"Satisfy these preconditions: {_task_preconditions(task)}. "
                            "Use only the visible OpenRA UI, then emit done."
                        ),
                        max_steps=max_steps,
                        observer=observer,
                        task_id=task.id,
                    )
                    before_shot = phase_a.screenshot
                    grader_accum_ms += int(phase_a.grader_ms)
                    if phase_a.incomplete:
                        _record_openra_seed_evidence(
                            result, runtime, initial=initial_seed
                        )
                        return _abort_incomplete_phase(
                            result,
                            phase_name="phase_a",
                            phase_a=phase_a,
                            phase_b=None,
                            time_to_start_ms=phase_a.elapsed_ms,
                            runtime_bootstrap_ms=runtime_bootstrap_ms,
                            grader_ms=int(grader_accum_ms),
                            initial_shot=initial_shot,
                            before_shot=before_shot,
                        )

                result["start_grading_started"] = True
                semantic_started = time.perf_counter()
                before_grade = (
                    runtime.grade_target(oracle_spec)
                    if gameplay_task
                    else runtime.grade_settings(oracle_start)
                )
                before_semantic_ok = before_grade.ok
                before_semantic_status = before_grade.status
                before_semantic_detail = {
                    "source": (
                        "openra_live_gameplay_probe_v1"
                        if gameplay_task
                        else "openra_public_settings_yaml"
                    ),
                    "live": before_grade.detail.get("process_alive") is True,
                    **before_grade.detail,
                }
                grader_accum_ms += int(
                    (time.perf_counter() - semantic_started) * 1000
                )
                time_to_start_ms = (
                    checkpoint_restore_ms if synthesized else phase_a.elapsed_ms
                )
                if not before_semantic_ok:
                    _record_openra_seed_evidence(
                        result, runtime, initial=initial_seed
                    )
                    return _finish_start_gate_failure(
                        result,
                        phase_a=phase_a,
                        before_shot=before_shot,
                        initial_shot=initial_shot,
                        before_semantic_ok=False,
                        before_semantic_status=before_semantic_status,
                        before_semantic_detail=before_semantic_detail,
                        before_verdict=None,
                        time_to_start_ms=time_to_start_ms,
                        checkpoint_synthesis_ms=checkpoint_synthesis_ms,
                        checkpoint_restore_ms=checkpoint_restore_ms,
                        runtime_bootstrap_ms=runtime_bootstrap_ms,
                        grader_ms=int(grader_accum_ms),
                    )

                result["visual_grading_started"] = True
                visual_started = time.perf_counter()
                verdict, runtime_hold = _run_before_visual_gate(
                    runtime=runtime,
                    before_shot=str(before_shot),
                    goldens=goldens,
                    task=task,
                    result=result,
                )
                grader_accum_ms += int(
                    (time.perf_counter() - visual_started) * 1000
                )
                result["start_grading_runtime_hold"] = runtime_hold
                before_visual_ok, _ = _verdict_flags(verdict)
                if not before_visual_ok:
                    _record_openra_seed_evidence(
                        result, runtime, initial=initial_seed
                    )
                    return _finish_start_gate_failure(
                        result,
                        phase_a=phase_a,
                        before_shot=before_shot,
                        initial_shot=initial_shot,
                        before_semantic_ok=True,
                        before_semantic_status=before_semantic_status,
                        before_semantic_detail=before_semantic_detail,
                        before_verdict=verdict,
                        time_to_start_ms=time_to_start_ms,
                        checkpoint_synthesis_ms=checkpoint_synthesis_ms,
                        checkpoint_restore_ms=checkpoint_restore_ms,
                        runtime_bootstrap_ms=runtime_bootstrap_ms,
                        grader_ms=int(grader_accum_ms),
                    )
                result["start_gate_status"] = "passed"
                result["before_visual_status"] = "evaluated"
                remaining = max_steps if synthesized else max(0, max_steps - phase_a.steps)
                if remaining:
                    result["policy_phase_started"] = True
                    phase_b = _run_phase(
                        runtime=runtime,
                        client=client,
                        phase_dir=task_dir / "phase-b",
                        instruction=_public_phase_b_instruction(
                            task,
                            environment_instruction=(
                                "Complete the task through the visible OpenRA UI."
                            ),
                        ),
                        max_steps=remaining,
                        observer=observer,
                        task_id=task.id,
                    )
                else:
                    phase_b = PhaseResult(
                        reached=False,
                        steps=0,
                        screenshot=before_shot,
                        elapsed_ms=0,
                    )
                after_shot = phase_b.screenshot
                grader_accum_ms += int(phase_b.grader_ms)
                if phase_b.incomplete:
                    _record_openra_seed_evidence(
                        result, runtime, initial=initial_seed
                    )
                    return _abort_incomplete_phase(
                        result,
                        phase_name="phase_b",
                        phase_a=phase_a,
                        phase_b=phase_b,
                        time_to_start_ms=time_to_start_ms,
                        checkpoint_synthesis_ms=checkpoint_synthesis_ms,
                        checkpoint_restore_ms=checkpoint_restore_ms,
                        runtime_bootstrap_ms=runtime_bootstrap_ms,
                        grader_ms=int(grader_accum_ms),
                        initial_shot=initial_shot,
                        before_shot=before_shot,
                        before_semantic_ok=before_semantic_ok,
                        before_semantic_status=before_semantic_status,
                        before_semantic_detail=before_semantic_detail,
                        before_verdict=verdict,
                    )
                semantic_started = time.perf_counter()
                after_grade = runtime.grade_assertions(
                    semantic_assertions(oracle_spec) or []
                )
                after_semantic_ok = after_grade.ok
                after_semantic_status = after_grade.status
                after_semantic_detail = {
                    "source": (
                        "openra_live_gameplay_probe_v1"
                        if gameplay_task
                        else "openra_public_settings_yaml"
                    ),
                    "live": after_grade.detail.get("process_alive") is True,
                    **after_grade.detail,
                }
                grader_accum_ms += int(
                    (time.perf_counter() - semantic_started) * 1000
                )
                _record_openra_seed_evidence(
                    result, runtime, initial=initial_seed
                )
        except Exception as error:
            result.update(
                status="failed",
                incomplete=True,
                reason=f"OpenRA C1 GUI runtime failed: {error}",
            )
            return result

    grader_started = time.perf_counter()
    if (
        verdict is not None
        and before_shot
        and after_shot
        and Path(before_shot).exists()
        and Path(after_shot).exists()
    ):
        verdict = _run_after_visual_grade(
            before_verdict=verdict,
            before_shot=before_shot,
            after_shot=after_shot,
            goldens=goldens,
            task=task,
        )
    before_visual_ok, after_visual_ok = _verdict_flags(verdict)
    grader_ms = int(
        grader_accum_ms + (time.perf_counter() - grader_started) * 1000
    )
    start_success = bool(before_visual_ok and before_semantic_ok)
    goal_success = bool(after_visual_ok and after_semantic_ok)
    e2e_success = bool(start_success and goal_success)
    incomplete = bool(
        not _verdict_is_complete(verdict)
        or phase_a.incomplete
        or phase_b.incomplete
        or before_semantic_status in {"not_run", "validate_error"}
        or after_semantic_status in {"not_run", "validate_error"}
    )
    test_ms = phase_a.elapsed_ms + phase_b.elapsed_ms
    excluding_ms = test_ms + checkpoint_restore_ms
    including_ms = excluding_ms + checkpoint_synthesis_ms
    result.update(
        {
            "result": e2e_success,
            "status": "incomplete" if incomplete else ("success" if e2e_success else "failure"),
            "incomplete": incomplete,
            "before_visual_ok": bool(before_visual_ok),
            "before_semantic_ok": bool(before_semantic_ok),
            "after_visual_ok": bool(after_visual_ok),
            "after_semantic_ok": bool(after_semantic_ok),
            "start_success": start_success,
            "goal_success": goal_success,
            "e2e_success": e2e_success,
            "before_ok": bool(before_visual_ok),
            "semantic_ok": bool(after_semantic_ok),
            "stage2_pass": goal_success,
            "stage2_visual_pass": bool(after_visual_ok),
            "e2e_pass": e2e_success,
            "visual_only_upper_bound": bool(before_visual_ok and after_visual_ok),
            "visual_only_evaluation_status": "evaluated",
            "start_gate_status": "passed",
            "goal_evaluation_status": "evaluated",
            "before_visual_status": "evaluated",
            "after_visual_status": "evaluated",
            "before_semantic_status": before_semantic_status,
            "before_semantic_detail": before_semantic_detail,
            "after_semantic_status": after_semantic_status,
            "after_semantic_detail": after_semantic_detail,
            "semantic_status": after_semantic_status,
            "semantic_detail": after_semantic_detail,
            "semantic_probe_source": (
                "openra_live_gameplay_probe_v1"
                if gameplay_task
                else "openra_public_settings_yaml"
            ),
            "policy_action_interface": "pixel_mouse_keyboard_only",
            "policy_received_semantic_probe": False,
            "policy_observation_source": "application_framebuffer_pixels",
            "scripted_transition_executed": False,
            "time_to_start_ms": checkpoint_restore_ms if synthesized else phase_a.elapsed_ms,
            "time_start_to_goal_ms": phase_b.elapsed_ms,
            "time_e2e_excluding_synthesis_ms": excluding_ms,
            "time_e2e_including_synthesis_ms": including_ms,
            "termination_time_ms": including_ms,
            "checkpoint_synthesis_ms": checkpoint_synthesis_ms,
            "checkpoint_restore_ms": checkpoint_restore_ms,
            "runtime_bootstrap_ms": runtime_bootstrap_ms,
            "grader_ms": grader_ms,
            "wall_ms": test_ms,
            "steps": {
                "phase_a": phase_a.steps,
                "phase_b": phase_b.steps,
                "total": phase_a.steps + phase_b.steps,
            },
            "decision_budget": max_steps,
            "budget_exhausted": phase_a.steps + phase_b.steps >= max_steps,
            "initial_state_screenshot_hash": _screenshot_fingerprint(initial_shot),
            "screenshot_before": before_shot,
            "screenshot_after": after_shot,
            "pair_verdict": verdict,
            "phase_a_actions": phase_a.actions,
            "phase_b_actions": phase_b.actions,
        }
    )
    return result


def _luanti_semantic_grade(
    session: LuantiWarmSession,
    oracle_spec: dict[str, Any],
    *,
    after: bool,
) -> tuple[bool, str, dict[str, Any]]:
    assertions = semantic_assertions(oracle_spec) if after else []
    validation_spec = oracle_spec
    if after:
        # The live post-action world is expected to differ from the start target
        # (notably dig-node and replace-node).  Fast-restore normally validates the
        # target before assertions, which would reject those correct goal states.
        # For after grading, require only that the same world is live, then evaluate
        # the oracle's goal assertions without synthesizing or mutating anything.
        validation_spec = {**oracle_spec, "target": {"kind": "world_loaded"}}
    try:
        outcome = session.fast_restore(
            validation_spec,
            actions=[],
            assertions=assertions,
        )
    except Exception as error:
        return False, "validate_error", {"error": str(error)}
    ok = outcome.status == "success"
    return bool(ok), ("success" if ok else str(outcome.status)), {
        "status": outcome.status,
        "detail": outcome.detail,
        "checks": outcome.checks,
    }


def _run_luanti_agent_task(
    base: Path,
    task: StateLoopTask,
    *,
    model: str,
    base_url: str,
    api_key: str,
    api_key_env: str,
    synth_model: str,
    max_explore_steps: int,
    temperature: float,
    out_dir: Path,
    max_steps: int,
    start_mode: str,
    policy_kind: str,
    policy_client: Any | None,
    observer: FixedVisualBridge | None,
    seed: int,
    shared_synthesis_cache: Path | None = None,
) -> dict[str, Any]:
    """Run a C1 GUI policy against rendered Luanti with Quartz native input."""

    task_dir = out_dir / "tasks" / task.id
    result = _new_gui_result(
        task,
        start_mode=start_mode,
        policy_kind=policy_kind,
        model=model,
        seed=int(seed),
        max_steps=max_steps,
    )
    try:
        repo = resolve_task_repo(base, task.issue)
        oracle_spec_path = (base / task.oracle_spec).resolve()
        oracle_spec = _seed_spec(load_spec(oracle_spec_path), seed, benchmark=task.benchmark)
    except Exception as error:
        result.update(status="failed", incomplete=True, reason=f"task setup failed: {error}")
        return result
    result["validity_class"] = str(
        (oracle_spec.get("checkpoint") or {}).get("expected_validity") or "unclassified"
    )
    daylight_mode = luanti_daylight_mode_for_task(task, oracle_spec)
    result["luanti_daylight_mode"] = daylight_mode
    if not _attach_reference_replay_audit(
        result,
        base=base,
        task=task,
        repo=repo,
        oracle_spec=oracle_spec,
        oracle_spec_path=oracle_spec_path,
        seed=int(seed),
        headless=False,
    ):
        return result

    generated_spec: dict[str, Any] | None = None
    checkpoint_synthesis_ms = 0
    if start_mode in {"synthesized", "restored"}:
        synthesis = _obtain_self_synthesis(
            task,
            base=base,
            seed=int(seed),
            synth_model=synth_model,
            base_url=base_url,
            api_key_env=api_key_env,
            temperature=temperature,
            max_explore_steps=max_explore_steps,
            artifact_dir=task_dir / "synthesis-artifacts",
            policy_kind=policy_kind,
            shared_cache_root=shared_synthesis_cache,
        )
        generated_spec = _apply_self_synthesis_result(
            result,
            synthesis,
            task,
            seed=int(seed),
        )
        if generated_spec is None:
            return result
        checkpoint_synthesis_ms = int(result["checkpoint_synthesis_ms"])
        synth_spec_path = task_dir / "synth-spec.yaml"
        synth_spec_path.parent.mkdir(parents=True, exist_ok=True)
        synth_spec_path.write_text(
            yaml.safe_dump(generated_spec, sort_keys=False, allow_unicode=False),
            encoding="utf-8",
        )
        result["synthesized_spec"] = str(synth_spec_path)

    grader_accum_ms = 0
    verdict: dict[str, Any] | None = None
    golden_started = time.perf_counter()
    goldens = None
    # Luanti's formal rendered path uses the PID-owned Irrlicht background
    # input channel, so goldens and policy execution do not need Quartz focus.
    with contextlib.nullcontext():
        # Goldens are generated on their own rendered world.  The policy then gets a
        # fresh, same-seed world so oracle replay cannot leak the target state.
        try:
            if isinstance(repo, (str, Path)):
                goldens = lookup_cached_oracle_goldens(repo, oracle_spec)
            if goldens is None:
                with LuantiWarmSession(
                    repo,
                    task_dir / "goldens",
                    render=True,
                    experiment_seed=seed,
                    creative_mode=True,
                    daylight_mode=daylight_mode,
                ) as golden_session:
                    goldens = _ensure_luanti_goldens(
                        golden_session,
                        oracle_spec,
                        oracle_spec_path,
                        task_dir / "goldens",
                    )
        except Exception as error:
            result.update(
                status="failed",
                incomplete=True,
                reason=f"Luanti oracle golden generation failed: {error}",
            )
            return result
        grader_accum_ms += int((time.perf_counter() - golden_started) * 1000)
        result["oracle_goldens"] = _oracle_goldens_payload(goldens)

        boot_start = time.perf_counter()
        try:
            with LuantiWarmSession(
                repo,
                task_dir / "agent",
                render=True,
                experiment_seed=seed,
                creative_mode=True,
                daylight_mode=daylight_mode,
            ) as session:
                result["runtime_bootstrap_ms"] = int((time.perf_counter() - boot_start) * 1000)
                _record_luanti_seed_evidence(result, session)
                runtime = LuantiGuiRuntime(session)
                result["calibration"] = {"passed": True, **runtime.calibration_metadata()}
                initial_shot = runtime.screenshot(task_dir / "initial.png")
                if generated_spec is None and not _record_luanti_semantic_evidence(
                    result,
                    session,
                    task,
                    oracle_spec,
                    stage="entry",
                ):
                    result.update(
                        status="failed",
                        incomplete=True,
                        reason="Luanti live entry-state semantic probe failed",
                    )
                    return result
                client = policy_client or GuiAgentClient(
                    model=model,
                    base_url=base_url,
                    api_key=api_key,
                    api_key_env=api_key_env,
                    temperature=temperature,
                )

                if generated_spec is not None:
                    restore = session.restore(generated_spec, actions=[], assertions=[])
                    result["checkpoint_restore_ms"] = restore.elapsed_ms
                    result["restore_status"] = restore.status
                    result["time_to_start_ms"] = restore.elapsed_ms
                    result["time_e2e_excluding_synthesis_ms"] = restore.elapsed_ms
                    result["time_e2e_including_synthesis_ms"] = (
                        checkpoint_synthesis_ms + restore.elapsed_ms
                    )
                    result["termination_time_ms"] = (
                        checkpoint_synthesis_ms + restore.elapsed_ms
                    )
                    if restore.status != "success":
                        _mark_start_construction_fair_failure(
                            result, StartConstructionStatus.RESTORE_FAILED
                        )
                        result.update(
                            status="failure",
                            incomplete=False,
                            synth_status=restore.status,
                            reason=f"self-synthesized Luanti start did not restore: {restore.detail}",
                        )
                        return result
                    semantic_evidence_ok = _record_luanti_semantic_evidence(
                        result,
                        session,
                        task,
                        oracle_spec,
                        stage="restored",
                    )
                    if not semantic_evidence_ok:
                        result.update(
                            status="failed",
                            incomplete=True,
                            infrastructure_error=True,
                            reason="Luanti restored-state semantic probe failed",
                        )
                        return result
                    before_shot = runtime.screenshot(task_dir / "synth-start.png")
                    if not before_shot:
                        result.update(
                            status="failed",
                            incomplete=True,
                            infrastructure_error=True,
                            reason=(
                                "self-synthesized Luanti start restored but its "
                                "boundary screenshot was unavailable"
                            ),
                        )
                        return result
                    _set_start_construction_status(
                        result, StartConstructionStatus.REACHED
                    )
                    phase_a = PhaseResult(False, 0, before_shot, elapsed_ms=0)
                else:
                    result["policy_phase_started"] = True
                    phase_a = _run_phase(
                        runtime=runtime,
                        client=client,
                        instruction=(
                            f"Satisfy these preconditions: {_task_preconditions(task)}. "
                            "Then emit done."
                        ),
                        phase_dir=task_dir / "phase-a",
                        max_steps=max_steps,
                        observer=observer,
                        task_id=task.id,
                    )
                    before_shot = phase_a.screenshot
                grader_accum_ms += float(getattr(phase_a, "grader_ms", 0) or 0)
                if bool(getattr(phase_a, "incomplete", False)):
                    return _abort_incomplete_phase(
                        result,
                        phase_name="phase_a",
                        phase_a=phase_a,
                        phase_b=None,
                        time_to_start_ms=phase_a.elapsed_ms,
                        checkpoint_synthesis_ms=checkpoint_synthesis_ms,
                        checkpoint_restore_ms=int(
                            result.get("checkpoint_restore_ms", 0) or 0
                        ),
                        runtime_bootstrap_ms=int(
                            result.get("runtime_bootstrap_ms", 0) or 0
                        ),
                        grader_ms=int(grader_accum_ms),
                        initial_shot=initial_shot,
                        before_shot=before_shot,
                    )

                result["start_grading_started"] = True
                semantic_started = time.perf_counter()
                before_semantic_ok, before_semantic_status, before_semantic_detail = _luanti_semantic_grade(
                    session,
                    oracle_spec,
                    after=False,
                )
                grader_accum_ms += int((time.perf_counter() - semantic_started) * 1000)
                restore_ms = int(result.get("checkpoint_restore_ms", 0) or 0)
                start_time_ms = (
                    restore_ms if generated_spec is not None else phase_a.elapsed_ms
                )
                start_initial_shot = (
                    before_shot if generated_spec is not None else initial_shot
                )
                if not before_semantic_ok:
                    _record_luanti_seed_evidence(result, session)
                    return _finish_start_gate_failure(
                        result,
                        phase_a=phase_a,
                        before_shot=before_shot,
                        initial_shot=start_initial_shot,
                        before_semantic_ok=before_semantic_ok,
                        before_semantic_status=before_semantic_status,
                        before_semantic_detail=before_semantic_detail,
                        before_verdict=None,
                        time_to_start_ms=start_time_ms,
                        checkpoint_synthesis_ms=checkpoint_synthesis_ms,
                        checkpoint_restore_ms=restore_ms,
                        runtime_bootstrap_ms=int(
                            result.get("runtime_bootstrap_ms", 0) or 0
                        ),
                        grader_ms=int(grader_accum_ms),
                    )

                result["visual_grading_started"] = True
                before_visual_started = time.perf_counter()
                verdict, runtime_hold = _run_before_visual_gate(
                    runtime=runtime,
                    before_shot=str(before_shot),
                    goldens=goldens,
                    task=task,
                    result=result,
                    before_rubric=LUANTI_BEFORE_RUBRIC,
                )
                grader_accum_ms += int(
                    (time.perf_counter() - before_visual_started) * 1000
                )
                result["start_grading_runtime_hold"] = runtime_hold
                before_visual_ok, _ = _verdict_flags(verdict)
                if not before_visual_ok:
                    _record_luanti_seed_evidence(result, session)
                    return _finish_start_gate_failure(
                        result,
                        phase_a=phase_a,
                        before_shot=before_shot,
                        initial_shot=start_initial_shot,
                        before_semantic_ok=before_semantic_ok,
                        before_semantic_status=before_semantic_status,
                        before_semantic_detail=before_semantic_detail,
                        before_verdict=verdict,
                        time_to_start_ms=start_time_ms,
                        checkpoint_synthesis_ms=checkpoint_synthesis_ms,
                        checkpoint_restore_ms=restore_ms,
                        runtime_bootstrap_ms=int(
                            result.get("runtime_bootstrap_ms", 0) or 0
                        ),
                        grader_ms=int(grader_accum_ms),
                    )
                result["start_gate_status"] = "passed"
                result["before_visual_status"] = "evaluated"
                remaining = max_steps if generated_spec is not None else max(0, max_steps - phase_a.steps)
                if remaining:
                    result["policy_phase_started"] = True
                    phase_b = _run_phase(
                        runtime=runtime,
                        client=client,
                        instruction=_public_phase_b_instruction(
                            task,
                            environment_instruction=(
                                "Use only the visible Luanti UI."
                            ),
                        ),
                        phase_dir=task_dir / "phase-b",
                        max_steps=remaining,
                        observer=observer,
                        task_id=task.id,
                    )
                else:
                    phase_b = PhaseResult(
                        reached=False,
                        steps=0,
                        screenshot=phase_a.screenshot,
                        elapsed_ms=0,
                        incomplete=phase_a.incomplete,
                    )
                grader_accum_ms += float(getattr(phase_b, "grader_ms", 0) or 0)
                after_shot = phase_b.screenshot
                if bool(getattr(phase_b, "incomplete", False)):
                    restore_ms = int(result.get("checkpoint_restore_ms", 0) or 0)
                    return _abort_incomplete_phase(
                        result,
                        phase_name="phase_b",
                        phase_a=phase_a,
                        phase_b=phase_b,
                        time_to_start_ms=(
                            restore_ms
                            if generated_spec is not None
                            else phase_a.elapsed_ms
                        ),
                        checkpoint_synthesis_ms=checkpoint_synthesis_ms,
                        checkpoint_restore_ms=restore_ms,
                        runtime_bootstrap_ms=int(
                            result.get("runtime_bootstrap_ms", 0) or 0
                        ),
                        grader_ms=int(grader_accum_ms),
                        initial_shot=(
                            before_shot if generated_spec is not None else initial_shot
                        ),
                        before_shot=before_shot,
                        before_semantic_ok=before_semantic_ok,
                        before_semantic_status=before_semantic_status,
                        before_semantic_detail=before_semantic_detail,
                        before_verdict=verdict,
                    )
                semantic_started = time.perf_counter()
                after_semantic_ok, after_semantic_status, after_semantic_detail = _luanti_semantic_grade(
                    session,
                    oracle_spec,
                    after=True,
                )
                grader_accum_ms += int((time.perf_counter() - semantic_started) * 1000)
        except Exception as error:
            result.update(status="failed", incomplete=True, reason=f"Luanti GUI runtime failed: {error}")
            return result

    grader_start = time.perf_counter()
    if (
        verdict is not None
        and before_shot
        and after_shot
        and Path(before_shot).exists()
        and Path(after_shot).exists()
    ):
        verdict = _run_after_visual_grade(
            before_verdict=verdict,
            before_shot=before_shot,
            after_shot=after_shot,
            goldens=goldens,
            task=task,
            before_rubric=LUANTI_BEFORE_RUBRIC,
        )
    before_visual_ok, after_visual_ok = _verdict_flags(verdict)
    grader_ms = int(
        grader_accum_ms + (time.perf_counter() - grader_start) * 1000
    )
    start_success = bool(before_visual_ok and before_semantic_ok)
    goal_success = bool(after_visual_ok and after_semantic_ok)
    e2e_success = bool(start_success and goal_success)
    incomplete = bool(
        not _verdict_is_complete(verdict)
        or phase_a.incomplete
        or phase_b.incomplete
        or before_semantic_status == "validate_error"
        or after_semantic_status == "validate_error"
    )
    restore_ms = int(result.get("checkpoint_restore_ms", 0) or 0)
    test_ms = phase_a.elapsed_ms + phase_b.elapsed_ms
    e2e_excluding_synthesis_ms = test_ms + restore_ms
    including_ms = e2e_excluding_synthesis_ms + checkpoint_synthesis_ms
    result.update(
        {
            "result": e2e_success,
            "status": "incomplete" if incomplete else ("success" if e2e_success else "failure"),
            "incomplete": incomplete,
            "before_visual_ok": bool(before_visual_ok),
            "before_semantic_ok": bool(before_semantic_ok),
            "after_visual_ok": bool(after_visual_ok),
            "after_semantic_ok": bool(after_semantic_ok),
            "start_success": start_success,
            "goal_success": goal_success,
            "e2e_success": e2e_success,
            "before_ok": bool(before_visual_ok),
            "semantic_ok": bool(after_semantic_ok),
            "stage2_pass": goal_success,
            "stage2_visual_pass": bool(after_visual_ok),
            "e2e_pass": e2e_success,
            "visual_only_upper_bound": bool(before_visual_ok and after_visual_ok),
            "visual_only_evaluation_status": "evaluated",
            "start_gate_status": "passed",
            "goal_evaluation_status": "evaluated",
            "before_visual_status": "evaluated",
            "after_visual_status": "evaluated",
            "before_semantic_status": before_semantic_status,
            "before_semantic_detail": before_semantic_detail,
            "after_semantic_status": after_semantic_status,
            "after_semantic_detail": after_semantic_detail,
            "time_to_start_ms": phase_a.elapsed_ms + restore_ms,
            "time_start_to_goal_ms": phase_b.elapsed_ms,
            "time_e2e_excluding_synthesis_ms": e2e_excluding_synthesis_ms,
            "time_e2e_including_synthesis_ms": including_ms,
            "termination_time_ms": including_ms,
            "grader_ms": grader_ms,
            "wall_ms": test_ms,
            "steps": {"phase_a": phase_a.steps, "phase_b": phase_b.steps, "total": phase_a.steps + phase_b.steps},
            "decision_budget": max_steps,
            "budget_exhausted": phase_a.steps + phase_b.steps >= max_steps,
            "initial_state_screenshot_hash": _screenshot_fingerprint(
                before_shot if generated_spec is not None else initial_shot
            ),
            "screenshot_before": before_shot,
            "screenshot_after": after_shot,
            "pair_verdict": verdict,
            "phase_a_actions": phase_a.actions,
            "phase_b_actions": phase_b.actions,
        }
    )
    return result


def _summarize_agent(results: list[dict[str, Any]]) -> dict[str, Any]:
    total = len(results)
    passed = sum(1 for r in results if r.get("result"))
    stage2_passed = sum(1 for r in results if r.get("stage2_pass"))
    stage2_visual_passed = sum(1 for r in results if r.get("stage2_visual_pass"))
    semantic_passed = sum(1 for r in results if r.get("semantic_ok"))
    e2e_passed = sum(1 for r in results if r.get("e2e_pass"))
    steps = [r.get("steps", {}).get("total", 0) for r in results if isinstance(r.get("steps"), dict)]
    walls = [r.get("wall_ms", 0) for r in results if isinstance(r.get("wall_ms"), int)]
    cost_total = {"llm_calls": 0, "total_tokens": 0, "est_usd": None}
    prompt = completion = 0
    for r in results:
        c = r.get("cost") if isinstance(r.get("cost"), dict) else {}
        cost_total["llm_calls"] += int(c.get("llm_calls", 0) or 0)
        cost_total["total_tokens"] += int(c.get("total_tokens", 0) or 0)
        prompt += int(c.get("prompt_tokens", 0) or 0)
        completion += int(c.get("completion_tokens", 0) or 0)
    cost_total["est_usd"] = cost.estimate_usd(prompt, completion)
    return {
        "total_tasks": total,
        "passed": passed,
        "stage2_passed": stage2_passed,
        "stage2_visual_passed": stage2_visual_passed,
        "semantic_passed": semantic_passed,
        "e2e_passed": e2e_passed,
        "mean_steps": round(sum(steps) / len(steps), 2) if steps else None,
        "mean_wall_ms": round(sum(walls) / len(walls), 1) if walls else None,
        "cost": cost_total,
    }
