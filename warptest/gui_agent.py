def _verdict_flags(verdict: dict[str, Any] | None) -> tuple[bool, bool]:
    """Return (before_ok, after_ok) from a pair-audit verdict's per-half labels."""

    if not isinstance(verdict, dict):
        return False, False
    before_ok = isinstance(verdict.get("before"), dict) and verdict["before"].get("label") == "correct"
    after_ok = isinstance(verdict.get("after"), dict) and verdict["after"].get("label") == "correct"
    return bool(before_ok), bool(after_ok)


def _verdict_is_complete(verdict: dict[str, Any] | None) -> bool:
    if not isinstance(verdict, dict):
        return False
    before = verdict.get("before")
    if not isinstance(before, dict) or before.get("label") not in {"correct", "incorrect"}:
        return False
    # A definitive before failure completes the pair outcome by short circuit: the
    # goal must not be attempted or judged from a state that failed the start gate.
    if before.get("label") == "incorrect":
        return True
    after = verdict.get("after")
    return isinstance(after, dict) and after.get("label") in {"correct", "incorrect"}


def _before_only_verdict(verdict: dict[str, Any]) -> dict[str, Any]:
    """Normalize a mocked/legacy pair result to the staged before-only contract."""

    before = verdict.get("before") if isinstance(verdict, dict) else None
    before = dict(before) if isinstance(before, dict) else {
        "stage": "before",
        "label": "uncertain",
        "judge_failure": True,
    }
    before_ok = before.get("label") == "correct"
    return {
        **(verdict if isinstance(verdict, dict) else {}),
        "result": False,
        "status": "pending" if before_ok else "failure",
        "before": before,
        "after": {
            "stage": "after",
            "label": "not_evaluated",
            "evaluation_status": (
                "pending_phase_b"
                if before_ok
                else "not_evaluated_before_failed"
            ),
        },
        "after_evaluated": False,
    }


