def _produce_self_synthesis(
    task: StateLoopTask,
    *,
    base: Path,
    seed: int,
    clean_synth_model: str,
    synth_provider: Any,
    temperature: float,
    max_explore_steps: int,
    artifact_dir: Path,
    policy_kind: str,
    cache_key: dict[str, Any],
    cache_key_fingerprint: str,
) -> dict[str, Any]:
    synthesis_started = time.perf_counter()
    checkpoint: Any | None = None
    synthesis_error: Exception | None = None
    with cost.scoped_meter() as synthesis_meter:
        try:
            synth_agent = build_synthesis_agent(
                "llm",
                model=clean_synth_model,
                base_url=synth_provider.base_url,
                api_key_env=synth_provider.api_key_env,
                temperature=temperature,
                max_tokens=C1_SYNTHESIS_MAX_TOKENS,
                explore=C1_SYNTHESIS_EXPLORE,
                max_steps=max_explore_steps,
                extra_headers=synth_provider.extra_headers,
            )
            checkpoint = synth_agent.synthesize(
                task.issue,
                base,
                artifact_dir=artifact_dir,
            )
        except Exception as error:
            synthesis_error = error
    synthesis_ms = int((time.perf_counter() - synthesis_started) * 1000)
    synthesis_cost = synthesis_meter.summary()
    synthesis_audit: dict[str, Any] = {}
    synthesis_meta_path = artifact_dir / "synthesis-meta.json"
    if synthesis_meta_path.is_file():
        try:
            synthesis_meta = json.loads(
                synthesis_meta_path.read_text(encoding="utf-8")
            )
            if isinstance(synthesis_meta, dict):
                synthesis_audit = {
                    "initial_output_sha256": synthesis_meta.get(
                        "initial_output_sha256"
                    ),
                    "raw_response_path": synthesis_meta.get(
                        "raw_response_path"
                    ),
                    "formal_c1_finalization": synthesis_meta.get(
                        "formal_c1_finalization"
                    ),
                    "format_repair": synthesis_meta.get("format_repair"),
                    "repair_attempted": bool(
                        synthesis_meta.get("repair_attempted")
                        or (
                            isinstance(
                                synthesis_meta.get("formal_c1_finalization"),
                                dict,
                            )
                            and synthesis_meta["formal_c1_finalization"]
                            .get("repair", {})
                            .get("attempted")
                        )
                    ),
                }
        except Exception:
            synthesis_audit = {"meta_read_error": True}
    used_public_scaffold = bool(
        getattr(checkpoint, "used_public_scaffold", False)
        if checkpoint is not None
        else False
    )
    outcome: dict[str, Any]
    if synthesis_error is not None:
        infrastructure = bool(
            _is_infrastructure_error(synthesis_error)
            or synthesis_cost.get("usage_complete") is not True
        )
        outcome = synthesis_outcome(
            status="infrastructure_error" if infrastructure else "fair_failure",
            synth_status="synthesis_error",
            generated_spec=None,
            checkpoint=None,
            used_public_scaffold=used_public_scaffold,
            reason=f"self-synthesis of start checkpoint failed: {synthesis_error}",
        )
    else:
        acceptance = accept_c1_generated_spec(
            getattr(checkpoint, "model_generated_spec", None),
            issue=task.issue,
            benchmark=task.benchmark,
            seed=seed,
        )
        if not acceptance.accepted:
            provider_failure = _checkpoint_provider_failure(checkpoint)
            if provider_failure is not None:
                outcome = synthesis_outcome(
                    status="infrastructure_error",
                    synth_status="provider_failure",
                    generated_spec=None,
                    checkpoint=None,
                    used_public_scaffold=used_public_scaffold,
                    reason="self-synthesis provider failure: " + provider_failure,
                )
            else:
                outcome = synthesis_outcome(
                    status="fair_failure",
                    synth_status=acceptance.status,
                    generated_spec=None,
                    checkpoint=None,
                    used_public_scaffold=used_public_scaffold,
                    reason=acceptance.reason,
                    artifacts={"acceptance_errors": list(acceptance.errors)},
                )
        else:
            outcome = synthesis_outcome(
                status="success",
                synth_status="generated",
                generated_spec=acceptance.spec,
                checkpoint=_checkpoint_payload(checkpoint, acceptance.spec),
                used_public_scaffold=used_public_scaffold,
                reason=None,
            )
    return {
        "schema_version": SELF_SYNTHESIS_CACHE_SCHEMA_VERSION,
        "created_at_utc": datetime.now(timezone.utc).isoformat(),
        "cache_key": cache_key,
        "cache_key_fingerprint": cache_key_fingerprint,
        "producer": {
            "policy_kind": policy_kind,
            "artifact_dir": str(artifact_dir.resolve()),
        },
        "checkpoint_synthesis_ms": synthesis_ms,
        "synthesis_cost": synthesis_cost,
        "synthesis_audit": synthesis_audit,
        "outcome": outcome,
    }


def _obtain_self_synthesis(
    task: StateLoopTask,
    *,
    base: Path,
    seed: int,
    synth_model: str,
    base_url: str,
    api_key_env: str,
    temperature: float,
    max_explore_steps: int,
    artifact_dir: Path,
    policy_kind: str,
    shared_cache_root: Path | None,
) -> dict[str, Any]:
    try:
        clean_synth_model, synth_provider = resolve_model(
            synth_model,
            default_base_url=base_url,
            default_api_key_env=api_key_env,
        )
    except Exception as error:
        empty_cost = cost.CostMeter().summary()
        fallback_key = {
            "schema_version": SELF_SYNTHESIS_CACHE_SCHEMA_VERSION,
            "task_id": task.id,
            "seed": int(seed),
            "synth_model": synth_model,
        }
        return _materialize_self_synthesis(
            {
                "cache_key_fingerprint": _canonical_hash(fallback_key),
                "checkpoint_synthesis_ms": 0,
                "synthesis_cost": empty_cost,
                "producer": {"policy_kind": policy_kind},
                "outcome": synthesis_outcome(
                    status="infrastructure_error",
                    synth_status="configuration_error",
                    generated_spec=None,
                    checkpoint=None,
                    used_public_scaffold=False,
                    reason=f"self-synthesis provider resolution failed: {error}",
                ),
            },
            cache_hit=False,
            cache_path=None,
            checkout_root=base,
        )

    cache_key = _self_synthesis_cache_key(
        task,
        base=base,
        seed=seed,
        synth_model=clean_synth_model,
        provider_name=synth_provider.name,
        provider_base_url=synth_provider.base_url,
        temperature=temperature,
        max_tokens=C1_SYNTHESIS_MAX_TOKENS,
        explore=C1_SYNTHESIS_EXPLORE,
        max_explore_steps=max_explore_steps,
    )
    fingerprint = _canonical_hash(cache_key, length=32)

    def produce() -> dict[str, Any]:
        return _produce_self_synthesis(
            task,
            base=base,
            seed=seed,
            clean_synth_model=clean_synth_model,
            synth_provider=synth_provider,
            temperature=temperature,
            max_explore_steps=max_explore_steps,
            artifact_dir=artifact_dir,
            policy_kind=policy_kind,
            cache_key=cache_key,
            cache_key_fingerprint=fingerprint,
        )

    return obtain_synthesis(
        cache_key=cache_key,
        fingerprint=fingerprint,
        shared_cache_root=shared_cache_root,
        produce=produce,
        materialize=lambda payload, *, cache_hit, cache_path: (
            _materialize_self_synthesis(
                payload,
                cache_hit=cache_hit,
                cache_path=cache_path,
                checkout_root=base,
            )
        ),
        outcome_usable=_synthesis_outcome_usable,
    )


