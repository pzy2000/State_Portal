class GuiAgentClient:
    """Text decision policy fed by the fixed visual observer in formal C1 runs."""

    def __init__(
        self,
        *,
        model: str,
        base_url: str,
        api_key: str | None = None,
        api_key_env: str = "MODELSCOPE_API_KEY",
        temperature: float = 0.2,
        max_tokens: int = 8192,
        extra_headers: dict[str, str] | None = None,
        provider_timeout_s: float | None = None,
    ) -> None:
        from openai import OpenAI

        clean_model, provider = resolve_model(
            model,
            default_base_url=base_url,
            default_api_key_env=api_key_env,
        )
        resolved_key = os.environ.get(provider.api_key_env, "") or (api_key or "")
        if not resolved_key:
            raise RuntimeError(f"{provider.api_key_env} is required for the GUI decision policy.")
        self.model = clean_model
        self.provider_name = provider.name
        self.request_profile = resolve_model_request_profile(clean_model)
        self.temperature = temperature
        self.max_tokens = max_tokens
        # Reasoning models (e.g. gpt-5.5, claude-sonnet-5) reject a non-default
        # ``temperature``; once we see that 400 we drop it for the rest of the run
        # instead of failing every pixel step, mirroring the synthesis client.
        self._temperature_supported = True
        timeout = (
            float(provider_timeout_s)
            if provider_timeout_s is not None
            else float(os.environ.get("WARPTEST_GUI_AGENT_TIMEOUT", "300"))
        )
        max_retries = int(os.environ.get("WARPTEST_GUI_AGENT_MAX_RETRIES", "0"))
        self.max_retries = max_retries
        self.provider_timeout_s = timeout
        kwargs: dict[str, Any] = {
            "api_key": resolved_key,
            "base_url": provider.base_url,
            "timeout": timeout,
            "max_retries": max_retries,
        }
        headers = dict(provider.extra_headers)
        headers.update(extra_headers or {})
        if headers:
            kwargs["default_headers"] = headers
        self.client = OpenAI(**kwargs)

    def next_action(
        self,
        *,
        instruction: str,
        screenshot: Path,
        history: list[str],
        observation: str | None = None,
        width: int = VIEWPORT["width"],
        height: int = VIEWPORT["height"],
    ) -> AgentAction:
        prompt = _build_action_prompt(
            instruction=instruction,
            history=history,
            observation=observation,
            width=width,
            height=height,
        )
        user_content: Any
        if observation is None:
            # Backward-compatible direct-VLM mode for the standalone command.  Formal
            # P5/C1 always provides an observation and therefore sends text only.
            user_content = [
                {"type": "text", "text": prompt},
                {"type": "text", "text": "Current screenshot:"},
                {"type": "image_url", "image_url": {"url": image_data_url(screenshot)}},
            ]
        else:
            user_content = prompt
        messages = [
            {"role": "system", "content": "You are a computer-use agent operating a GUI by emitting one action at a time. Output strict JSON only."},
            {"role": "user", "content": user_content},
        ]
        try:
            _response, content, finish_reason, usage_fields = self._create_recorded(
                messages,
                max_tokens=self.max_tokens,
            )
        except Exception as error:
            if self._temperature_supported and _is_temperature_rejection(error):
                rejected_usage = cost.extract_usage(error)
                if rejected_usage is not None:
                    cost.record_usage_call(
                        self.model,
                        usage=rejected_usage,
                        content=None,
                        finish_reason=None,
                        reasoning_expected=(
                            self.request_profile.reasoning_expected
                        ),
                        reasoning_disabled=(
                            self.request_profile.profile == "thinking_disabled"
                        ),
                        latency_ms=0,
                        kind="gui_policy",
                        messages=messages,
                        requested_at=datetime.now(timezone.utc).isoformat(),
                    )
                self._temperature_supported = False
                print(f"[gui-agent] {self.model}: model rejected 'temperature'; retrying without it for the rest of the run.", flush=True)
                _response, content, finish_reason, usage_fields = self._create_recorded(
                    messages,
                    max_tokens=self.max_tokens,
                )
            else:
                raise
        if not content.strip() and str(finish_reason or "").lower() in {
            "length",
            "max_tokens",
        }:
            # Only an explicit output-limit finish reason proves exhaustion. A
            # reasoning-only response with ``stop`` is a model outcome, not grounds
            # for buying an otherwise identical 16k retry.
            _response, content, _finish_reason, _retry_usage = self._create_recorded(
                messages,
                max_tokens=16384,
            )
        if not content.strip():
            raise RuntimeError("GUI policy returned empty content")
        return parse_agent_action(content or "")

    def _create_recorded(
        self,
        messages: list[dict[str, Any]],
        *,
        max_tokens: int,
    ) -> tuple[Any, str, str | None, dict[str, int]]:
        requested_at = datetime.now(timezone.utc).isoformat()
        started = time.perf_counter()
        try:
            response = self._create(messages, max_tokens=max_tokens)
        except Exception as error:
            if self._temperature_supported and _is_temperature_rejection(error):
                raise
            latency_ms = int((time.perf_counter() - started) * 1000)
            try:
                cost.record_error_usage_call(
                    self.model,
                    error=error,
                    latency_ms=latency_ms,
                    kind="gui_policy",
                    messages=messages,
                    requested_at=requested_at,
                )
            except cost.UsageAccountingError as accounting_error:
                raise accounting_error from error
            # Preserve the provider-attempt ledger before translating a deadline
            # transport error into C1TaskTimeout (a BaseException).
            raise_task_timeout_if_expired(error)
            raise
        latency_ms = int((time.perf_counter() - started) * 1000)
        content, finish_reason = _message_content(response)
        usage = cost.record_usage_call(
            self.model,
            usage=getattr(response, "usage", None),
            content=content,
            finish_reason=finish_reason,
            reasoning_observed=cost.response_has_reasoning_content(response),
            reasoning_expected=self.request_profile.reasoning_expected,
            reasoning_disabled=(self.request_profile.profile == "thinking_disabled"),
            latency_ms=latency_ms,
            kind="gui_policy",
            messages=messages,
            requested_at=requested_at,
            response=content,
            endpoint="chat.completions",
            provider_reported_model=getattr(response, "model", None),
            provider_response_id=getattr(response, "id", None),
            system_fingerprint=getattr(response, "system_fingerprint", None),
        )
        return response, content, finish_reason, usage

    def _create(self, messages: list[dict[str, Any]], *, max_tokens: int | None = None):
        kwargs: dict[str, Any] = {
            "model": self.model,
            "messages": messages,
            "max_tokens": int(max_tokens or self.max_tokens),
        }
        if self._temperature_supported:
            kwargs["temperature"] = self.temperature
        kwargs.update(self.request_profile.request_kwargs())
        timeout_s = bounded_task_timeout_s(self.provider_timeout_s)
        request_client = (
            self.client.with_options(timeout=timeout_s)
            if current_task_deadline() is not None
            and hasattr(self.client, "with_options")
            else self.client
        )
        return request_client.chat.completions.create(**kwargs)


def _build_action_prompt(
    *,
    instruction: str,
    history: list[str],
    observation: str | None = None,
    width: int = VIEWPORT["width"],
    height: int = VIEWPORT["height"],
) -> str:
    payload = {
        "instruction": instruction,
        "viewport": {"width": int(width), "height": int(height)},
        "visual_observation": observation,
        "output_contract": {
            "action": "click|key|type|scroll|drag|wait|done|fail",
            "x": "int pixel x for click (0..width)",
            "y": "int pixel y for click (0..height)",
            "key": "key name for action=key, e.g. ArrowLeft, Enter, w",
            "dx": "scroll delta x for action=scroll",
            "dy": "scroll delta y for action=scroll",
            "x2": "drag destination pixel x for action=drag",
            "y2": "drag destination pixel y for action=drag",
            "text": "text for action=type; native Luanti accepts printable ASCII only",
            "modifiers": "optional key modifiers; use only [Shift]",
            "seconds": "wait duration, clamped to 0..30",
            "overwrite": "for type; must be false for native Luanti",
            "enter": "for type, press Enter after typing",
            "reason": "one short sentence",
        },
        "instructions": [
            "Use only the structured visual observation and emit exactly ONE next action as strict JSON.",
            "Use click with pixel coordinates to press on-screen buttons/tiles.",
            "Use key for keyboard-driven games (e.g. 2048 arrows, flight controls).",
            "Emit action=done only when the requested transition is visibly complete.",
            "Emit action=fail only when an unrecoverable blocker is clearly visible.",
            "Do not invent UI that is not visible. Return JSON only, no Markdown.",
        ],
        "recent_actions": history[-8:],
    }
    return json.dumps(payload, ensure_ascii=False, indent=2)


def parse_agent_action(content: str) -> AgentAction:
    body = content.strip()
    fence = re.search(r"```(?:json)?\s*(.*?)```", body, flags=re.IGNORECASE | re.DOTALL)
    if fence:
        body = fence.group(1).strip()
    try:
        data = json.loads(body)
    except Exception:
        # Best-effort: find the first {...} block.
        match = re.search(r"\{.*\}", body, flags=re.DOTALL)
        if not match:
            return AgentAction(kind="wait", raw=content[:200])
        try:
            data = json.loads(match.group(0))
        except Exception:
            return AgentAction(kind="wait", raw=content[:200])
    kind = str(data.get("action", "wait")).lower()
    modifiers_raw = data.get("modifiers") or []
    modifiers = tuple(str(item) for item in modifiers_raw) if isinstance(modifiers_raw, list) else ()
    return AgentAction(
        kind=kind if kind in {"click", "key", "type", "scroll", "drag", "wait", "done", "fail"} else "wait",
        x=_to_int(data.get("x")),
        y=_to_int(data.get("y")),
        key=str(data["key"]) if data.get("key") is not None else None,
        dx=_to_int(data.get("dx")),
        dy=_to_int(data.get("dy")),
        x2=_to_int(data.get("x2")),
        y2=_to_int(data.get("y2")),
        text=str(data["text"]) if data.get("text") is not None else None,
        modifiers=modifiers,
        seconds=float(data["seconds"]) if isinstance(data.get("seconds"), (int, float)) else None,
        duration=float(data["duration"]) if isinstance(data.get("duration"), (int, float)) else None,
        button=str(data["button"]) if data.get("button") is not None else None,
        clicks=_to_int(data.get("clicks")),
        overwrite=bool(data.get("overwrite", False)),
        enter=bool(data.get("enter", False)),
        raw=str(data.get("reason", ""))[:200],
    )


def _to_int(value: Any) -> int | None:
    try:
        return int(round(float(value)))
    except (TypeError, ValueError):
        return None


