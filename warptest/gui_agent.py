"""Real vision GUI-agent baseline (the PlayCoder / computer-use comparison).

This is the C1 baseline the paper argues against: a computer-use agent that drives a
GUI using only pixels -- it sees a screenshot, emits a raw
``click(x, y)`` / ``key`` / ``scroll`` / ``wait`` / ``done`` action, Playwright
executes it, and the loop repeats. No domain checkpoint hook or save injection is
available to a from-start policy; deterministic offline-service controls are installed
before navigation. The agent gets only public task text and screenshot-derived visual
observations. Production DOM/save probes are grader-only and never enter policy input.

Two start modes:

* ``from_start`` (default) -- the strict PlayCoder baseline. Phase A drives from the
  entry screen to the described start state (graded vs the oracle before-golden),
  Phase B performs the described transition (graded vs the after-golden). This carries
  the full "play from scratch" burden and is the strict lower bound.
* ``synthesized`` -- the *fair same-start* comparison. Rather than being handed the
  method's hidden validated start, the GUI arm must *construct its own* start: it runs
  the same checkpoint-synthesis stack the method uses (``build_synthesis_agent`` with
  the same model), synthesizes a ``generated_spec``, and injects that self-produced
  start on a warm ``StateSession`` (``restore(actions=[])``). The pixel agent then runs
  Phase B ONLY from that self-synthesized live state. This makes the GUI arm carry the
  *same start-construction burden* as the method (so ``before_ok`` -- did its own start
  actually match the golden -- can genuinely fail), while isolating goal completion for
  the after-half: even granted a self-built start, does the pixel agent complete the
  transition? The agent still acts through pixels only (mouse/keyboard), so it cannot
  call the injection hook during Phase B. ``restored`` is accepted as a legacy alias.

The task passes iff both halves are judged ``correct`` under the same visual judge used
by the state-managed loop. We additionally record a decomposed ``stage2_pass`` (the
after-half / transition succeeded) and ``e2e_pass`` (both halves) so the same-start
success rate can be reported separately from end-to-end success. Steps, wall-clock, and
LLM cost are recorded to expose error/hallucination accumulation over long horizons.

Oracle goldens are generated by the state-managed path first. In ``from_start`` mode a
closed StateSession makes the goldens and the agent then runs on its own hook-free
BrowserRuntimeAdapter (the two Playwright sessions never overlap). In ``synthesized``
mode a single warm StateSession makes the goldens, then the GUI arm synthesizes and
injects its OWN start state (never the hidden oracle start) and hands the live page to
the pixel agent for Phase B. The hidden ``oracle_spec`` is still used only to generate
goldens and to select committed, allow-listed grader assertions. Love/SpaceRPG A--D
semantics come from production UI/persistence surfaces rather than private state hooks.
"""
