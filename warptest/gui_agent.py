def _bind_task_random_control(
    result: dict[str, Any],
    task: StateLoopTask,
) -> None:
    control = copy.deepcopy(getattr(task.issue, "random_control", {}) or {})
    result["random_control"] = control
    evidence = result.get("seed_evidence")
    if not isinstance(evidence, dict):
        evidence = _runtime_not_started_seed_evidence(task.benchmark)
        result["seed_evidence"] = evidence
    evidence["random_control"] = copy.deepcopy(control)
    mode = control.get("mode")
    if mode == "not_applicable":
        evidence["randomness"] = "not_applicable"
        evidence["seed_role"] = "trial_pairing_only"
        evidence.setdefault("seed", result.get("seed"))
        valid = bool(
            evidence.get("observed") is True
            and evidence.get("randomness") == "not_applicable"
            and evidence.get("seed_role") == "trial_pairing_only"
            and evidence.get("seed") == result.get("seed")
        )
    else:
        valid = bool(
            mode == "experiment_seed"
            and evidence.get("observed") is True
            and evidence.get("algorithm") == control.get("algorithm")
            and evidence.get("seed") == result.get("seed")
            and result.get("seed") in (control.get("seeds") or [])
        )
    result["random_control_evidence_valid"] = valid


def _record_browser_seed_evidence(
    result: dict[str, Any],
    *,
    initial: Any,
    final: Any | None = None,
) -> None:
    """Attach evidence read from the live browser page.

    No constructor/request defaults are filled here: a missing/invalid readback stays
    unobserved and will fail the formal C1 gate.
    """

    initial_snapshot = dict(initial) if isinstance(initial, dict) else {}
    final_snapshot = dict(final) if isinstance(final, dict) else None
    initial_observed = initial_snapshot.get("observed") is True
    final_observed = final_snapshot is None or final_snapshot.get("observed") is True
    result["runtime_started"] = True
    result["seed_evidence"] = {
        "schema_version": 1,
        "source": "browser_page_runtime",
        "observed": bool(initial_observed and final_observed),
        "algorithm": initial_snapshot.get("algorithm"),
        "seed": initial_snapshot.get("seed"),
        "initial": initial_snapshot,
        "final": final_snapshot,
    }
    result["prng"] = final_snapshot or initial_snapshot or None


def _record_luanti_seed_evidence(result: dict[str, Any], session: LuantiWarmSession) -> None:
    """Attach values observed from the real warm-session config/world/process."""

    try:
        observed = session.seed_metadata()
    except Exception:
        observed = None
    snapshot = dict(observed) if isinstance(observed, dict) else {}
    previous = result.get("seed_evidence")
    semantic_evidence = {
        key: value
        for key, value in (
            previous.items() if isinstance(previous, dict) else ()
        )
        if key == "semantic_observed" or key.startswith("initial_semantic_")
    }
    evidence = {"schema_version": 1, **snapshot, **semantic_evidence}
    evidence["observed"] = bool(
        snapshot.get("observed") is True
        and (
            not semantic_evidence
            or semantic_evidence.get("semantic_observed") is True
        )
    )
    result["runtime_started"] = True
    result["seed_evidence"] = evidence
    result["prng"] = snapshot or None


