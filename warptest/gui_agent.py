class StartConstructionStatus(str, Enum):
    """Producer-owned state for the B/D self-constructed start treatment.

    ``not_applicable`` is exclusive to from-start A/C. Synthesized B/D starts at
    ``pending`` and may finish as a deterministic fair zero (``synthesis_failed``
    or ``restore_failed``) or as ``reached`` once its generated candidate restores.
    Infrastructure/provider failures remain ``pending`` with ``incomplete=true``;
    a complete trial must never escape with ``pending``.
    """

    NOT_APPLICABLE = "not_applicable"
    PENDING = "pending"
    SYNTHESIS_FAILED = "synthesis_failed"
    RESTORE_FAILED = "restore_failed"
    REACHED = "reached"


def _set_start_construction_status(
    result: dict[str, Any], status: StartConstructionStatus
) -> None:
    if not isinstance(status, StartConstructionStatus):
        raise TypeError("start construction status must be StartConstructionStatus")
    result["start_construction_status"] = status.value


def _mark_start_construction_fair_failure(
    result: dict[str, Any], status: StartConstructionStatus
) -> None:
    if status not in {
        StartConstructionStatus.SYNTHESIS_FAILED,
        StartConstructionStatus.RESTORE_FAILED,
    }:
        raise ValueError("fair construction failure requires a failed terminal status")
    _set_start_construction_status(result, status)
    result["start_gate_status"] = "not_evaluated_start_construction_failed"
    result["goal_evaluation_status"] = "not_evaluated_start_construction_failed"
    result["visual_only_evaluation_status"] = (
        "not_evaluated_start_construction_failed"
    )


