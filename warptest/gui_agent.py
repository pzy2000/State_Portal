def _gui_retry_category(result: dict[str, Any]) -> str | None:
    reason = str(result.get("reason") or "")
    retry_category = run_context.error_category(RuntimeError(reason))
    # ``infrastructure_error`` is produced only by the controlled exception /
    # runtime classifiers above. Preserve that typed evidence even when the
    # scrubbed user-facing reason (for example final_screenshot_capture_failed)
    # does not itself contain one of run_context's transport markers.
    if result.get("infrastructure_error") is True:
        return retry_category or "infra"
    return retry_category


def _gui_trial_retryable_incomplete(result: dict[str, Any]) -> bool:
    if result.get("incomplete") is not True or cost.contains_unknown_usage(result):
        return False
    if result.get("infrastructure_error") is True:
        return _gui_retry_category(result) is not None
    # Before policy execution, a specifically classified provider/runtime outage
    # can be retried without selecting among stochastic completed trajectories.
    if result.get("policy_phase_started") is not True:
        return _gui_retry_category(result) is not None
    return False


def _gui_retry_metadata(result: dict[str, Any]) -> tuple[str | None, str | None]:
    """Return scrubbed retry provenance only for an allow-listed outage."""

    if result.get("retryable_incomplete") is not True:
        return None, None
    reason = str(result.get("reason") or "")
    category = _gui_retry_category(result)
    if category not in {"infra", "rate_limit"}:
        return None, None
    marker = "service unavailable" if category == "infra" else "rate limit"
    scrubbed = run_context.safe_error_text(reason, limit=450)
    return category, f"{marker}: {scrubbed}"[:500]


def _gui_report_incomplete_contract(
    results: list[dict[str, Any]],
) -> tuple[bool, str | None]:
    incomplete = [item for item in results if item.get("incomplete") is True]
    if not incomplete:
        return False, None
    if cost.contains_unknown_usage(incomplete):
        return False, "permanent_unknown_usage"
    if all(item.get("retryable_incomplete") is True for item in incomplete):
        return True, "transient_infrastructure"
    return False, "nonretryable_incomplete_evidence"


